"""Write thesis/ch7/FIGURES.md (one line per Chapter 7 figure) and thesis/ch7/figures/preview.tex (every float).

    uv run python thesis/scripts/ch7_figures_index.py
    cd thesis/ch7/figures && latexmk -pdf preview.tex && latexmk -c     # the preview PDF

Scans the floats on disk (thesis/ch7/figures/sections/figures/{used,options}/*.tex, written by the generators
through thesis/ch7/figlib.py): label, caption, file and generator are read from each float; "pairs with" (the
tables a figure sits beside) from the candidate gallery's manifest (thesis/ch7/figure_candidates/out/manifest.json).
Nothing is typed per figure.
"""
from __future__ import annotations

import json
import re
from pathlib import Path

REPO = Path(__file__).resolve().parents[2]
CH7 = REPO / "thesis/ch7"
ROOT = CH7 / "figures"
OUT = CH7 / "FIGURES.md"
PREVIEW = ROOT / "preview.tex"
MANIFEST = CH7 / "figure_candidates/out/manifest.json"

LABEL = re.compile(r"\\label\{([^}]+)\}")
GRAPHIC = re.compile(r"\\includegraphics\[[^\]]*\]\{([^}]+)\}")
GEN = re.compile(r"% Generated by (\S+)")


def caption_of(src: str) -> str:
    i = src.index("\\caption{") + len("\\caption{")
    depth, j = 1, i
    while depth:
        depth += {"{": 1, "}": -1}.get(src[j], 0)
        j += 1
    return src[i:j - 1]


def preamble() -> str:
    """The uathesis preview preamble of thesis/ch7/exp1/preview.tex (read, not retyped)."""
    src = (CH7 / "exp1/preview.tex").read_text()
    head = src[:src.index("\\begin{document}")]
    return "\n".join(ln for ln in head.splitlines() if not ln.startswith("%"))


def main():
    pairs = {m["id"]: m.get("pairs_with", "") for m in json.loads(MANIFEST.read_text())}
    rows = {"used": [], "options": []}
    for g in rows:
        for t in sorted((ROOT / "sections/figures" / g).glob("*.tex")):
            src = t.read_text()
            graphic = GRAPHIC.search(src).group(1)
            ext = Path(graphic).suffix or ".pdf"
            f = ROOT / (graphic if Path(graphic).suffix else graphic + ".pdf")
            assert f.exists(), f
            rows[g].append(dict(id=t.stem, label=LABEL.search(src).group(1), caption=caption_of(src),
                                file=str(f.relative_to(REPO)), float=str(t.relative_to(REPO)),
                                gen=GEN.search(src).group(1), raster=ext == ".png", pairs=pairs.get(t.stem, "")))
    L = ["# Chapter 7: figures", "",
         "Generated by `uv run python thesis/scripts/ch7_figures_index.py` from the floats on disk; do not edit by "
         "hand. **used**: the figures picked for the chapter (`USED` in `thesis/ch7/figlib.py`); **options**: every "
         "other figure, kept for the results text. Each figure is a vector PDF (`.png` beside it at 300 dpi) and a "
         "generated float; the Overleaf upload (`thesis/scripts/build_overleaf_upload.sh`) places them at "
         "`figures/ch7/<group>/<id>.pdf` and `sections/figures/<group>/<id>.tex`, the paths the floats use. "
         "Preview of every float: `thesis/ch7/figures/preview.pdf`. Captions are a title and the keys only; "
         "the text taken out of them is in `thesis/ch7/CAPTION_MOVED_TEXT.md`. Chain per figure: "
         "`thesis/ch7/PROVENANCE.md`.", ""]
    for g, title in (("used", "Used"), ("options", "Options")):
        L += [f"## {title} ({len(rows[g])})", "", "| Label | File | Pairs with | Caption | Generator |",
              "|---|---|---|---|---|"]
        for r in rows[g]:
            cap = r["caption"].replace("|", "\\|").replace("\n", " ")
            note = " (raster PNG: no vector source)" if r["raster"] else ""
            L.append(f"| `{r['label']}` | `{r['file']}`{note} | {r['pairs'] or '--'} | {cap} | `{r['gen']}` |")
        L.append("")
    OUT.write_text("\n".join(L))

    P = ["% Generated by thesis/scripts/ch7_figures_index.py -- every Chapter 7 figure float (used, then options).",
         "% Preamble: thesis/ch7/exp1/preview.tex (uathesis print layout). Paths as in the Overleaf upload.",
         preamble(), "\\begin{document}"]
    for g, title in (("used", "Used"), ("options", "Options")):
        P.append(f"\\chapter*{{Chapter 7 figures: {title.lower()}}}")
        for k, r in enumerate(rows[g]):
            P.append(f"\\input{{sections/figures/{g}/{r['id']}}}")
            if k % 2 == 1:
                P.append("\\clearpage")
        P.append("\\clearpage")
    P.append("\\end{document}\n")
    PREVIEW.write_text("\n".join(P))
    print(f"wrote {OUT.relative_to(REPO)} ({len(rows['used'])} used, {len(rows['options'])} options) and "
          f"{PREVIEW.relative_to(REPO)}")


if __name__ == "__main__":
    main()
