"""Experiment 1, MONK-2: does each model's explanation state the rule "exactly two of the six attributes take
their first value"? PropNEAT's original network against EBMs and decision trees (layer 3: formats only).

    uv run python thesis/ch7/exp1/monk2_rule_table.py

Reads:
  * experiments/monk2_rule_comparison/results/monk2_rules.json (fit_models.py): the comparators' test AUC,
    explanation size and rule check, and the original network's explanation as read from its plain-language
    layer (parts, the two active units, the rule check);
  * experiments/benchmarks/results/propneat.json: the original network's test AUC (recomputed from its genome,
    equal to its run record); its genome is asserted to be the one of the plain-language layer;
  * thesis/ch7/exp1/data/networks.json (extract_db.py, read-only DB): the original network's parts (leaf and
    composition annotations) and inputs, asserted equal to the layer's.
Writes tables/exp1-monk2-rules.tex (tab:exp1-monk2-rules). Overleaf: sections/tables/ch7-ex1-monk2-rules.tex.
"""
from __future__ import annotations

import json
from pathlib import Path

HERE = Path(__file__).resolve().parent
REPO = HERE.parents[2]
RULES = REPO / "experiments" / "monk2_rule_comparison" / "results" / "monk2_rules.json"
PROPNEAT = REPO / "experiments" / "benchmarks" / "results" / "propneat.json"
NETWORKS = HERE / "data" / "networks.json"
OUT = HERE / "tables" / "exp1-monk2-rules.tex"
GEN = "thesis/ch7/exp1/monk2_rule_table.py"

# rows in order: (model key in monk2_rules.json, printed model)
ROWS = [("ebm_onehot", "EBM"), ("ebm_raw", "EBM"), ("tree_onehot", "Tree"), ("tree_raw", "Tree"),
        ("tree_count", "Tree"), ("ebm_count", "EBM")]
INPUTS = {"one-hot": "one-hot", "raw": "raw", "count": "count"}


def f3(x):
    return f"{float(x):.3f}"


def ebm_size(s):
    terms = "term" if s["n_terms"] == 1 else "terms"
    parts = [f"{s['n_main']} main"] + ([f"{s['n_pairs']} pairs"] if s["n_pairs"] else [])
    detail = f" ({', '.join(parts)})" if s["n_pairs"] else ""
    return f"{s['n_terms']} {terms}{detail}", f"{s['terms_for_80pct']} / {s['terms_for_95pct']}"


def rule(v):
    """The rule column, wrapped after its first two words (layout only)."""
    w = v.split()
    return v if len(w) <= 2 else f"\\makecell[l]{{{' '.join(w[:2])}\\\\{' '.join(w[2:])}}}"


def tree_size(s):
    return f"depth {s['depth']}, {s['leaves']} leaves", "--"


def main():
    R = json.loads(RULES.read_text())
    P = R["propneat"]
    pn = json.loads(PROPNEAT.read_text())["exp1"]["paper-monk2"]
    net = json.loads(NETWORKS.read_text())["networks"]["paper-monk2"]
    assert pn["genome_id"] == P["genome_id"] == net["genome"], (pn["genome_id"], P["genome_id"], net["genome"])
    assert net["explanation_id"] == P["explanation_id"]
    assert (net["leaf"], net["comp"], len(net["parts"])) == (P["n_leaf"], P["n_composition"], P["n_parts"]), net
    assert net["n_inputs"] == len(R["data"]["onehot"])
    cov = " / ".join(f"{round(c * 100)}\\%" for c in R["cover"])

    rows = [("PropNEAT$^\\dagger$", f"one-hot ({net['n_inputs']})", f3(pn["test_auc"]),
             f"{P['n_parts']} parts ({P['n_leaf']} {'leaf' if P['n_leaf'] == 1 else 'leaves'}, "
             f"{P['n_composition']} composition{'' if P['n_composition'] == 1 else 's'})", "--",
             rule(P["rule_stated"]))]
    for key, name in ROWS:
        m = R["models"][key]
        size, cover = (ebm_size if m["size"]["kind"] == "ebm" else tree_size)(m["size"])
        rows.append((name, f"{INPUTS[m['inputs']]} ({m['n_inputs']})", f3(m["test_auc"]), size, cover,
                     rule(m["rule_stated"])))

    body = ["  \\setlength{\\tabcolsep}{5pt}", "  \\renewcommand{\\arraystretch}{1.15}",
            "  \\begin{tabular}{@{}llclcl@{}}", "    \\toprule",
            "    Model & Inputs & \\makecell{Test\\\\AUC} & Explanation size & "
            f"\\makecell{{Terms for\\\\{cov}}} & \\makecell[l]{{Rule\\\\stated?}} \\\\",
            "    \\midrule"]
    for i, r in enumerate(rows):
        body.append("    " + " & ".join(r) + " \\\\")
        if i == 0:
            body.append("    \\midrule")
    body += ["    \\bottomrule", "  \\end{tabular}"]
    cap = ("MONK-2: whether each model's explanation states the rule (exactly two of the six attributes at their "
           "first value). $^\\dagger$Original network. Inputs (number): one-hot, the one-hot columns; raw, the six "
           "attributes; count, the number of attributes at their first value. EBM: explainable boosting machine; "
           f"Tree: decision tree. Terms for {cov}: the fewest terms holding that share of the EBM's total term "
           "importance. Only given the count: stated when the count is an input, or when the model's log-odds "
           "are grouped by the count; --: not applicable.")
    src = (f"% Generated by {GEN} -- do not edit by hand.\n"
           "\\begin{table}[tbp]\n  \\thesistablestyle\n  \\centering\n  \\footnotesize\n" + "\n".join(body)
           + f"\n  \\caption{{{cap}}}\n  \\label{{tab:exp1-monk2-rules}}\n\\end{{table}}\n")
    OUT.write_text(src)
    print(f"wrote {OUT.relative_to(REPO)}")


if __name__ == "__main__":
    main()
