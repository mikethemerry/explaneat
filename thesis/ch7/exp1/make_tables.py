"""Experiment 1 thesis tables (read-only; every number from a results file, none typed).

    uv run python thesis/ch7/exp1/extract_db.py     # data/networks.json (read-only DB), when stale
    uv run python thesis/ch7/exp1/make_tables.py    # tables/*.tex
    (preview: cd thesis/ch7/exp1 && latexmk -pdf preview.tex)

Outputs:
    tables/exp1-networks.tex    one row per dataset's explained network, the columns of Experiment 2's
                                ten-run tables (thesis/ch7/exp2/per_run.py); landscape
    tables/exp1-benchmarks.tex  each dataset's PropNEAT network against the comparator suite
                                (experiments/benchmarks/benchmarks.csv; benchmark_tables.py, shared
                                with Experiment 2's exp2-benchmarks.tex)
Sources: data/networks.json (extract_db.py), experiments/benchmarks/results/propneat.json and
survival.json, experiments/benchmarks/benchmarks.csv, experiments/ushape_saddle/references.json
(the synthetic sets' true-logit AUC, quoted in a caption).
"""
from __future__ import annotations

import json
import statistics as st
from pathlib import Path

import benchmark_tables as bt

HERE = Path(__file__).resolve().parent
REPO = HERE.parents[2]
TAB = HERE / "tables"
BENCH = REPO / "experiments" / "benchmarks"


def jload(p):
    return json.loads(Path(p).read_text())


def num(x, d=3):
    if x is None:
        return "--"
    s = f"{x:.{d}f}"
    return "$-$" + s[1:] if s.startswith("-") else s


def sci(x):
    if x == 0:
        return "0"
    m, e = f"{x:.1e}".split("e")
    return f"${m}\\times10^{{{int(e)}}}$"


def write(name, src):
    TAB.mkdir(parents=True, exist_ok=True)
    (TAB / f"{name}.tex").write_text(f"% Generated by thesis/ch7/exp1/make_tables.py -- do not edit by hand.\n{src}")


# the rows of the per-network table, in the order of the chapter's Experiment 1
ORDER = [("paper-heart", "Heart (paper genome)$^\\dagger$"), ("paper-monk2", "MONK-2 (paper genome)$^\\dagger$"),
         ("cox-whas500-s0", "WHAS500 (Cox)$^\\ast$"), ("c4cap-main-h10-e50-s1", "Connect-4, cells (s1)"),
         ("c4lf-lines-heavy-s0", "Connect-4, lines (s0)"), ("shape-A", "Synthetic U (s0)"),
         ("shape-B", "Synthetic saddle (s0)"), ("shape-C", "Synthetic U $+$ saddle (s4)")]

HEAD = (r"Network & \makecell{Train\\AUC} & \makecell{Test AUC\\(95\% CI)} & \makecell{Inputs\\used} & "
        r"\makecell{Hidden\\nodes} & \makecell{Enabled\\conn.} & \makecell{Skippiness\\(skip conn.)} & "
        r"Density & Depth & \makecell{Leaf $+$\\comp.} & Splits & \makecell{Id.\\nodes} & "
        r"\makecell{Coverage\\struct./comp.} & \makecell{Function\\pres.\ error} & \makecell{Agent\\min} & "
        r"\makecell{Mike\\min}")


def table_networks():
    N = jload(HERE / "data" / "networks.json")
    P = jload(BENCH / "results" / "propneat.json")["exp1"]
    S = jload(BENCH / "results" / "survival.json")["whas500"]["propneat"]
    body = ["  \\setlength{\\tabcolsep}{2.5pt}", "  \\renewcommand{\\arraystretch}{1.15}",
            "  \\begin{adjustbox}{max width=\\textheight}",
            "  \\begin{tabular}{@{}l" + "c" * 15 + "@{}}", "    \\toprule", f"    {HEAD} \\\\", "    \\midrule"]
    for lab, name in ORDER:
        r = N["networks"][lab]
        if lab.startswith("cox-"):
            tr, te, lo, hi = S["train_harrell_c"], S["harrell_c"], *S["harrell_c_ci95"]
        else:
            p = P[lab]
            tr, te, (lo, hi) = p["train_auc"], p["test_auc"], p["test_auc_ci95"]
        cells = [name, num(tr), f"{num(te)} {{\\scriptsize [{num(lo)}, {num(hi)}]}}", f"{r['inputs']}/{r['n_inputs']}",
                 str(r["hidden"]), str(r["conns"]), f"{num(r['skippiness'], 2)} ({r['skips']})", num(r["density"], 3),
                 str(r["depth"]), f"{r['leaf']} $+$ {r['comp']}", str(r["splits"]), str(r["identity"]),
                 f"{num(r['cov_s'], 2)}/{num(r['cov_c'], 2)}", sci(r["fp"]), num(r["agent"], 1),
                 "--" if r["mike"] is None else num(r["mike"], 0)]
        body.append("    " + " & ".join(cells) + " \\\\")
    X = N["xor"]
    mr = lambda k, d=None: (f"\\makecell{{{(num(st.median(x[k] for x in X), d) if d else f'{st.median(x[k] for x in X):g}')}"  # noqa: E731
                            f"\\\\{{\\scriptsize {(num(min(x[k] for x in X), d) if d else min(x[k] for x in X))}--"
                            f"{(num(max(x[k] for x in X), d) if d else max(x[k] for x in X))}}}}}")
    n_ok = sum(x["train_accuracy"] == 1.0 for x in X)
    assert n_ok == len(X)
    body += ["    \\midrule",
             "    " + " & ".join([f"\\makecell[l]{{XOR$^\\ddagger$, {len(X)} seeds\\\\median (range)}}",
                                  "\\makecell{acc.\\\\1.000}", "--", f"{X[0]['inputs']}/{X[0]['n_inputs']}",
                                  mr("hidden"), mr("conns"),
                                  f"\\makecell{{{num(st.median(x['skippiness'] for x in X), 2)}\\\\{{\\scriptsize "
                                  f"{num(min(x['skippiness'] for x in X), 2)}--{num(max(x['skippiness'] for x in X), 2)}}}}}",
                                  mr("density", 3), mr("depth"), "--", "--", "--", "--", "--", "--", "--"]) + " \\\\",
             "    \\bottomrule", "  \\end{tabular}", "  \\end{adjustbox}"]
    paper = [N["networks"][k] for k in ("paper-heart", "paper-monk2")]
    v4 = [N["networks"][k] for k, _ in ORDER if not k.startswith("paper-")]
    assert all(r["mike"] is None for r in N["networks"].values())
    assert {r["protocol"] for r in paper} == {paper[0]["protocol"]} and len({r["protocol"] for r in v4}) == 1
    cap = ("Experiment 1: the explained network of each dataset, with the columns of the Experiment 2 run "
           "tables. Selection: the paper genomes are the AAAI paper's; WHAS500 is the lowest validation Cox "
           "loss of five seeds; Connect-4 and the synthetic sets are the largest training AUC of their runs "
           "(seed in brackets). AUCs and intervals are recomputed from each genome on its study's split "
           "(10{,}000 bootstrap resamples of the test rows) and equal the study's run record. "
           f"$^\\ast$WHAS500 is a Cox model: its train and test columns are Harrell's $C$. "
           "\\emph{Inputs used}, \\emph{hidden nodes}, \\emph{enabled connections}, \\emph{depth} and "
           "\\emph{skip connections} are of the phenotype; \\emph{skippiness} and \\emph{density} are the "
           "library's \\texttt{ExplaNEAT} measures on the genome, as in Experiment 2. Explanation columns are "
           "of the stored explanation: leaf $+$ composition annotations, node splits, identity nodes, "
           "structural / compositional coverage and the function-preservation error (largest absolute "
           "difference between the explained model and the network on the training rows). Every explanation "
           "except the two paper ones was written by one explaining agent with the frozen authoring method "
           "(v4, provenance-stamped); \\emph{agent min} is its wall-clock time from the record (Connect-4 "
           "cells includes a short sandbox pause). $^\\dagger$The paper explanations (July 2026) predate that "
           "method and record no explaining time; MONK-2's compositional coverage is 0.75 as stored because "
           "its pruned-input annotation sits outside the root. No Experiment 1 explanation has recorded "
           "verification minutes, so \\emph{Mike min} is blank throughout. "
           f"$^\\ddagger$XOR has no test set (the four rows are the whole truth table): each of the {len(X)} "
           "seeds' first solving genome, reduced to its minimal form (exact relay collapse and greedy pruning), "
           f"classifies all four rows ({n_ok} of {len(X)}); its realisations were analysed by hand, not annotated.")
    write("exp1-networks", "\\begin{sidewaystable}\n  \\centering\n  \\footnotesize\n" + "\n".join(body)
          + f"\n  \\caption{{{cap}}}\n  \\label{{tab:exp1-networks}}\n\\end{{sidewaystable}}\n")


DATASETS = [("heart", "Heart"), ("monk2", "MONK-2"), ("c4_cells", "\\makecell{Connect-4\\\\cells}"),
            ("c4_lines", "\\makecell{Connect-4\\\\lines}"), ("shape_u", "\\makecell{Synth.\\\\U}"),
            ("shape_saddle", "\\makecell{Synth.\\\\saddle}"), ("shape_both", "\\makecell{Synth.\\\\U $+$ saddle}")]


PLAIN = {"heart": "Heart", "monk2": "MONK-2", "c4_cells": "Connect-4 cells", "c4_lines": "Connect-4 lines",
         "shape_u": "U", "shape_saddle": "saddle", "shape_both": "U $+$ saddle"}


def thousands(x):
    return f"{int(x):,}".replace(",", "{,}")


def table_benchmarks():
    R = bt.rows()
    K = bt.by_key(R)
    us = jload(REPO / "experiments" / "ushape_saddle" / "references.json")
    xor = {k: K[("xor", k)] for k in ("propneat_explained", "lr_l2", "tree")}
    cls = bt.classification_table(DATASETS, [("propneat_explained", "Explained network", None)], R)
    surv = bt.survival_table(R)
    S = jload(BENCH / "results" / "survival.json")
    acc = jload(BENCH / "results" / "propneat.json")["exp1"]["xor"]["train_accuracy_all"]
    n_ok = sum(a == 1.0 for a in acc)
    xor_note = f"all {len(acc)} PropNEAT seeds" if n_ok == len(acc) else f"{n_ok} of {len(acc)} PropNEAT seeds"
    n = {d: (K[(d, "lr_l2")]["n_train"], K[(d, "lr_l2")]["n_test"]) for d, _ in DATASETS}
    cap = ("Experiment 1: each dataset's explained PropNEAT network against the comparator suite (binary "
           "classification; the survival case is Table~\\ref{tab:exp1-benchmarks-survival}). " + bt.SUITE_CAPTION
           + " Training / test rows: "
           + "; ".join(f"{PLAIN[d]} {thousands(n[d][0])} / {thousands(n[d][1])}" for d, _ in DATASETS)
           + ". On the synthetic sets the true logit reaches a test AUC of "
           + ", ".join(f"{us[t]['oracle']['test_auc']:.3f}" for t in ("u", "saddle", "both"))
           + " (U, saddle, U $+$ saddle). XOR (four rows, no test set): "
           f"{xor_note} classify the four rows; an $L_2$ logistic regression gets "
           f"{float(xor['lr_l2']['test_value']):.2f} (it predicts one class) and a decision tree "
           f"{float(xor['tree']['test_value']):.2f}.")
    cap_s = ("Experiment 1, survival: the explained PropNEAT Cox network of WHAS500 against Cox and survival-"
             "ensemble comparators on the Cox case's split "
             f"({S['whas500']['n_train']} training / {S['whas500']['n_test']} test patients, "
             f"{S['whas500']['events_test']} test events; the networks' {S['whas500']['n_val_unused']} validation "
             "patients are not used by the comparators). Each comparator is tuned by 5-fold cross-validation on the "
             "training rows, stratified on the event indicator (seed 42, scoring Harrell's $C$; the unpenalised Cox "
             "model has nothing to tune), refitted on all training rows and scored once on the test rows. Harrell's "
             "$C$ with its 95\\% percentile interval (10{,}000 bootstrap resamples of the test rows, "
             "\\texttt{RandomState(42)}); td-AUC: mean time-dependent AUC at 1, 3 and 5 years; IBS: integrated "
             "Brier score (lower is better). The Cox models' survival curves use the Breslow baseline on their "
             "training log-risks, as the networks'; the forest and the boosted model use their own. Bold: the "
             "column's best $C$. GBSG2, the other Cox case "
             f"({S['gbsg2']['n_train']} / {S['gbsg2']['n_test']}), is shown for comparison only.")
    src = ("\\begin{table}[tbp]\n  \\centering\n  \\footnotesize\n" + "\n".join(cls)
           + f"\n  \\caption{{{cap}}}\n  \\label{{tab:exp1-benchmarks}}\n\\end{{table}}\n\n"
           + "\\begin{table}[tbp]\n  \\centering\n  \\footnotesize\n" + "\n".join(surv)
           + f"\n  \\caption{{{cap_s}}}\n  \\label{{tab:exp1-benchmarks-survival}}\n\\end{{table}}\n")
    write("exp1-benchmarks", src)


def main():
    table_networks()
    table_benchmarks()
    print("tables:", ", ".join(sorted(p.stem for p in TAB.glob("*.tex"))))


if __name__ == "__main__":
    main()
