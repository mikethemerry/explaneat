from __future__ import annotations

import json
import statistics as st
from pathlib import Path

import benchmark_tables as bt

HERE = Path(__file__).resolve().parent
REPO = HERE.parents[2]
TAB = HERE / "tables"
BENCH = REPO / "experiments" / "benchmarks"


def jload(p):
    return json.loads(Path(p).read_text())


def num(x, d=3):
    if x is None:
        return "--"
    s = f"{x:.{d}f}"
    return "$-$" + s[1:] if s.startswith("-") else s


def write(name, src):
    TAB.mkdir(parents=True, exist_ok=True)
    (TAB / f"{name}.tex").write_text(f"% Generated by thesis/ch7/exp1/make_tables.py -- do not edit by hand.\n{src}")


# the rows of the per-network table, in the order of the chapter's Experiment 1
ORDER = [("paper-heart", "Heart (original network)$^\\dagger$"), ("paper-adult", "Adult (original network)$^\\dagger$"),
         ("paper-monk2", "MONK-2 (original network)$^\\dagger$"),
         ("cox-whas500-s0", "WHAS500 (Cox)$^\\ast$"), ("c4cap-main-h10-e50-s1", "Connect-4, cells (s1)"),
         ("c4lf-lines-heavy-s0", "Connect-4, lines (s0)"), ("shape-A", "Synthetic U (s0)"),
         ("shape-B", "Synthetic saddle (s0)"), ("shape-C", "Synthetic U $+$ saddle (s4)")]

HEAD = (r"Network & \makecell{Train\\AUC} & \makecell{Test AUC\\(95\% CI)} & \makecell{Inputs\\used} & "
        r"\makecell{Hidden\\nodes} & \makecell{Enabled\\conn.} & \makecell{Skippiness\\(skip conn.)} & "
        r"Density & Depth & \makecell{Leaf $+$\\comp.} & Splits & \makecell{Id.\\nodes} & "
        r"\makecell{Coverage\\struct./comp.} & \makecell{Agent\\min} & "
        r"\makecell{Verif.\\min}")


ORIGINAL = ("paper-heart", "paper-adult", "paper-monk2")


def perf(lab, r, P):
    """Train / test AUC of a classification network: experiments/benchmarks/results/propneat.json, or, for a
    network it does not hold yet (the original Adult network, 21 Nov 2026), extract_db.py's own read-only
    computation (the code of experiments/10seed/runs_paper_reference.csv, asserted equal to it). When both
    exist they must agree."""
    own = r.get("perf")
    if lab in P:
        p = P[lab]
        if own is not None:
            assert p["genome_id"] == r["genome"], lab
            for k in ("train_auc", "test_auc"):
                assert abs(p[k] - own[k]) < 1e-9, (lab, k, p[k], own[k])
            assert all(abs(a - b) < 1e-9 for a, b in zip(p["test_auc_ci95"], own["test_auc_ci95"])), lab
        return p
    assert own is not None, (lab, "no AUC in propneat.json or networks.json")
    return own


def table_networks():
    N = jload(HERE / "data" / "networks.json")
    P = jload(BENCH / "results" / "propneat.json")["exp1"]
    S = jload(BENCH / "results" / "survival.json")["whas500"]["propneat"]
    body = ["  \\setlength{\\tabcolsep}{2.5pt}", "  \\renewcommand{\\arraystretch}{1.15}",
            "  \\begin{adjustbox}{max width=\\textheight}",
            "  \\begin{tabular}{@{}l" + "c" * 14 + "@{}}", "    \\toprule", f"    {HEAD} \\\\", "    \\midrule"]
    for lab, name in ORDER:
        r = N["networks"][lab]
        if lab.startswith("cox-"):
            tr, te, lo, hi = S["train_harrell_c"], S["harrell_c"], *S["harrell_c_ci95"]
        else:
            p = perf(lab, r, P)
            tr, te, (lo, hi) = p["train_auc"], p["test_auc"], p["test_auc_ci95"]
        cells = [name, num(tr), f"{num(te)} {{\\scriptsize [{num(lo)}, {num(hi)}]}}", f"{r['inputs']}/{r['n_inputs']}",
                 str(r["hidden"]), str(r["conns"]), f"{num(r['skippiness'], 2)} ({r['skips']})", num(r["density"], 3),
                 str(r["depth"]), f"{r['leaf']} $+$ {r['comp']}", str(r["splits"]), str(r["identity"]),
                 f"{num(r['cov_s'], 2)}/{num(r['cov_c'], 2)}", num(r["agent"], 1),
                 "--" if r["mike"] is None else num(r["mike"], 0)]
        body.append("    " + " & ".join(cells) + " \\\\")
    X = N["xor"]
    mr = lambda k, d=None: (f"\\makecell{{{(num(st.median(x[k] for x in X), d) if d else f'{st.median(x[k] for x in X):g}')}"  # noqa: E731
                            f"\\\\{{\\scriptsize {(num(min(x[k] for x in X), d) if d else min(x[k] for x in X))}--"
                            f"{(num(max(x[k] for x in X), d) if d else max(x[k] for x in X))}}}}}")
    n_ok = sum(x["train_accuracy"] == 1.0 for x in X)
    assert n_ok == len(X)
    body += ["    \\midrule",
             "    " + " & ".join([f"\\makecell[l]{{XOR$^\\ddagger$, {len(X)} seeds\\\\median (range)}}",
                                  "\\makecell{acc.\\\\1.000}", "--", f"{X[0]['inputs']}/{X[0]['n_inputs']}",
                                  mr("hidden"), mr("conns"),
                                  f"\\makecell{{{num(st.median(x['skippiness'] for x in X), 2)}\\\\{{\\scriptsize "
                                  f"{num(min(x['skippiness'] for x in X), 2)}--{num(max(x['skippiness'] for x in X), 2)}}}}}",
                                  mr("density", 3), mr("depth"), "--", "--", "--", "--", "--", "--"]) + " \\\\",
             "    \\bottomrule", "  \\end{tabular}", "  \\end{adjustbox}"]
    paper = [N["networks"][k] for k in ORIGINAL]
    v4 = [N["networks"][k] for k, _ in ORDER if not k.startswith("paper-")]
    assert all(r["mike"] is None for r in N["networks"].values())
    assert {r["protocol"] for r in paper} == {paper[0]["protocol"]} and len({r["protocol"] for r in v4}) == 1
    # the caption's statements about the computed values
    assert all(r["agent"] is None for r in paper) and all(r["agent"] is not None for r in v4)
    # MONK-2's and Adult's pruned-input annotations are exempt from the single-root rule (D4): full
    # compositional coverage now, below 1 under the stored stream's earlier definition
    for k in ("paper-monk2", "paper-adult"):
        mk = N["networks"][k]
        assert mk["cov_c"] == 1.0 and mk["exempt_disconnected"] and mk["rec_cov_c"] < 1.0, mk
    assert all(not r["exempt_disconnected"] for k, r in N["networks"].items() if k not in ("paper-monk2", "paper-adult"))
    assert [k for k, _ in ORDER if k.startswith("paper-")] == list(ORIGINAL)
    # Caption: title and keys only (Mike, 20 Nov); the removed method and results sentences are kept in
    # thesis/ch7/CAPTION_MOVED_TEXT.md for the body text.
    cap = ("Experiment 1: the explained network of each dataset. (s$k$): seed $k$; --: none or not recorded. "
           "$^\\ast$Cox model: the train and test columns are Harrell's $C$. "
           "$^\\dagger$Original network and explanation. "
           "$^\\ddagger$No test set; acc.: accuracy on the four rows.")
    write("exp1-networks", "\\begin{sidewaystable}\n  \\thesistablestyle\n  \\centering\n  \\footnotesize\n" + "\n".join(body)
          + f"\n  \\caption{{{cap}}}\n  \\label{{tab:exp1-networks}}\n\\end{{sidewaystable}}\n")


DATASETS = [("heart", "Heart"), ("monk2", "MONK-2"), ("c4_cells", "\\makecell{Connect-4\\\\cells}"),
            ("c4_lines", "\\makecell{Connect-4\\\\lines}"), ("shape_u", "\\makecell{Synth.\\\\U}"),
            ("shape_saddle", "\\makecell{Synth.\\\\saddle}"), ("shape_both", "\\makecell{Synth.\\\\U $+$ saddle}")]


def table_benchmarks():
    R = bt.rows()
    cls = bt.classification_table(DATASETS, [("propneat_explained", "Explained network", None)], R)
    surv = bt.survival_table(R)
    # Captions: title and keys only (Mike, 20 Nov); the removed sentences are in CAPTION_MOVED_TEXT.md.
    cap = "Experiment 1: each dataset's explained PropNEAT network against the comparators. " + bt.SUITE_KEY
    cap_s = ("Experiment 1, survival: the explained PropNEAT Cox network of WHAS500 against the comparators. "
             "Harrell's $C$ with its 95\\% interval; td-AUC: mean time-dependent AUC; IBS: integrated Brier "
             "score (lower is better). Bold: the column's best $C$.")
    src = ("\\begin{table}[tbp]\n  \\thesistablestyle\n  \\centering\n  \\footnotesize\n" + "\n".join(cls)
           + f"\n  \\caption{{{cap}}}\n  \\label{{tab:exp1-benchmarks}}\n\\end{{table}}\n\n"
           + "\\begin{table}[tbp]\n  \\thesistablestyle\n  \\centering\n  \\footnotesize\n" + "\n".join(surv)
           + f"\n  \\caption{{{cap_s}}}\n  \\label{{tab:exp1-benchmarks-survival}}\n\\end{{table}}\n")
    write("exp1-benchmarks", src)


def main():
    table_networks()
    table_benchmarks()
    print("tables:", ", ".join(sorted(p.stem for p in TAB.glob("*.tex"))))


if __name__ == "__main__":
    main()
