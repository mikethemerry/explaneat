"""Experiment 2: a compact per-data-set summary of the signal-completeness check.

Reads experiments/signal_completeness/summary.json (written by completeness.py; formatting only) and
writes tables/exp2/exp2-signal-completeness.tex. Not part of the Overleaf upload.

    uv run python thesis/ch7/exp2/completeness_table.py
"""
from __future__ import annotations

import json
from pathlib import Path

HERE = Path(__file__).resolve().parent
REPO = HERE.parents[2]
SRC = REPO / "experiments/signal_completeness/summary.json"
OUT = HERE / "tables/exp2/exp2-signal-completeness.tex"
NAMES = {"adult": "Adult", "churn": "Churn", "heart100": "Heart-100"}


def f3(x):
    return f"{x:.3f}"


def main():
    S = json.loads(SRC.read_text())
    sets = [k for k in NAMES if k in S]
    rows = [
        ("Logit $R^2$ on the signals, train: median (min)", lambda s: f"{f3(s['r2_train_median'])} ({f3(s['r2_train_min'])})"),
        ("Logit $R^2$, test: median (min)", lambda s: f"{f3(s['r2_test_median'])} ({f3(s['r2_test_min'])})"),
        ("Linear terms alone, $R^2$ train (median)", lambda s: f3(s["r2_linear_train_median"])),
        ("Residual SD (logit), train: median (max)", lambda s: f"{f3(s['resid_sd_train_median'])} ({f3(s['resid_sd_train_max'])})"),
        ("Networks with residual SD $\\geq 0.10$", lambda s: f"{len(s['networks_resid_sd_ge_0_10'])} of {s['n_networks']}"),
        ("Parts used (all)", lambda s: f"{s['n_parts_used']} ({s['n_parts']})"),
        ("Parts mapping to no signal", lambda s: str(s["n_parts_unmapped"])),
        ("Mapped parts with residual SD $\\geq 0.10$", lambda s: str(s["n_parts_mapped_with_residual"])),
        ("Candidate signals in the residual", lambda s: str(s["n_candidates"])),
        ("Complete by the criterion", lambda s: "yes" if s["complete"] else "no"),
    ]
    body = [f"    {lab} & " + " & ".join(fn(S[k]) for k in sets) + r" \\" for lab, fn in rows]
    cap = ("Is each signal list complete? Each network's logit is projected on the data functions of "
           "its table's signals (training rows). Complete when every network's residual has an SD "
           "below 0.10 logit and the residual scan (one variable and variable pairs, permutation "
           "tested) finds no candidate signal. Source: \\texttt{experiments/signal\\_completeness}.")
    tex = "\n".join([
        "% Generated by thesis/ch7/exp2/completeness_table.py -- do not edit by hand.",
        r"\begin{table}", r"  \thesistablestyle", r"  \centering", r"  \footnotesize",
        r"  \begin{tabular}{@{}l" + "c" * len(sets) + "@{}}", r"    \toprule",
        "    & " + " & ".join(NAMES[k] for k in sets) + r" \\", r"    \midrule", *body,
        r"    \bottomrule", r"  \end{tabular}", rf"  \caption{{{cap}}}", r"  \label{tab:exp2-signal-completeness}",
        r"\end{table}", ""])
    OUT.write_text(tex)
    print("wrote", OUT.relative_to(REPO))


if __name__ == "__main__":
    main()
