def fig_pairs():
    plt = mpl()
    import matplotlib.colors as mcolors
    from explaneat.analysis.feature_labels import codebook_for, feature_label
    P = json.loads((DATA / "pairs_s2.json").read_text())
    inputs = P["inputs"]
    cb = codebook_for("Heart Disease (binary, prepared)", [i["name"] for i in inputs])
    labs = []
    for i in inputs:
        fl = feature_label(cb, i["name"])
        if fl["kind"] == "one-hot":
            labs.append(fl["label"].replace(" on the thallium scan", "").replace("no chest pain (asymptomatic)", "no chest pain"))
        else:
            labs.append(fl.get("short") or fl["label"])
        if fl.get("unit") and fl["kind"] != "one-hot" and fl["unit"] not in labs[-1]:
            labs[-1] += f" ({fl['unit']})"
    k = len(inputs)
    zall = np.concatenate([np.ravel(p["z"]) for p in P["pairs"]] + [np.ravel(i["pd"]) for i in inputs])
    norm = mcolors.TwoSlopeNorm(vcenter=0.5, vmin=min(0.0, zall.min()), vmax=max(1.0, zall.max()))
    cmap = plt.get_cmap("RdBu_r")
    fig, axes = plt.subplots(k, k, figsize=(TEXTWIDTH_IN, TEXTWIDTH_IN * 0.92))
    pair = {(p["a"], p["b"]): p for p in P["pairs"]}

    def edges(i):
        gx = np.asarray(inputs[i]["grid"])
        if inputs[i]["kind"] == "continuous":
            mid = (gx[1:] + gx[:-1]) / 2
            return np.concatenate([[gx[0] - (mid[0] - gx[0])], mid, [gx[-1] + (gx[-1] - mid[-1])]])
        return np.arange(len(gx) + 1) - 0.5

    def ticks(ax, i, axis):
        inp = inputs[i]
        if inp["kind"] == "binary":
            (ax.set_xticks if axis == "x" else ax.set_yticks)([0, 1], ["no", "yes"])
        elif inp["kind"] == "discrete":
            gx = inp["grid"]
            (ax.set_xticks if axis == "x" else ax.set_yticks)(range(len(gx)), [g(v) for v in gx])
    im = None
    for r in range(k):
        for c in range(k):
            ax = axes[r, c]
            ax.grid(False)
            if r == c:
                inp = inputs[r]
                gx = np.asarray(inp["grid"])
                xx = gx if inp["kind"] == "continuous" else np.arange(len(gx))
                ax.plot(xx, inp["pd"], color="black", lw=1.1, marker=None if inp["kind"] == "continuous" else "o", ms=3)
                ax.axhline(0.5, color="0.6", lw=0.5, ls=":")
                ax.set_ylim(0, 1)
                ax.set_yticks([0, 0.5, 1])
                ticks(ax, r, "x")
                ex = edges(r)
                ax.set_xlim(ex[0], ex[-1])
            elif r > c:
                p = pair.get((c, r))
                z = np.asarray(p["z"]).T   # rows: input r, cols: input c
                im = ax.pcolormesh(edges(c), edges(r), z, cmap=cmap, norm=norm, shading="flat")
                ticks(ax, c, "x")
                ticks(ax, r, "y")
            else:
                p = pair.get((r, c))
                ax.set_axis_off()
                ax.text(0.5, 0.5, f"$H$ = {p['h']:.2f}", ha="center", va="center", fontsize=7.5,
                        transform=ax.transAxes)
                continue
            if r < k - 1:
                ax.set_xticklabels([])
            else:
                ax.set_xlabel(labs[c], fontsize=7)
            if c > 0:
                ax.set_yticklabels([])
            else:
                ax.set_ylabel(labs[r] if r else "risk", fontsize=7)
            ax.tick_params(labelsize=6, length=2)
    axes[0, 0].set_ylabel("predicted risk", fontsize=7)
    fig.subplots_adjust(left=0.1, right=0.9, bottom=0.08, top=0.98, wspace=0.12, hspace=0.12)
    cax = fig.add_axes([0.92, 0.25, 0.015, 0.5])
    cb_ = fig.colorbar(im, cax=cax)
    cb_.set_label("predicted risk of heart disease", fontsize=7)
    cb_.ax.tick_params(labelsize=6)
    save(fig, "exp2-heart-pairs")
    top = P["pairs"][0]
    write_figure("exp2-heart-pairs",
                 "Heart-100 seed 2, the whole model: a pairs plot over the five inputs it is most sensitive "
                 "to. Diagonal: predicted risk as one input varies; below the diagonal: as two vary together "
                 "(colour, centred on a risk of 0.5); other inputs held at their training median, which is a "
                 f"reference patient with a predicted risk of {num(P['reference'], 2)}. Above the diagonal: "
                 "the strength of each pair's interaction ($H$, the share of the pair's variation not explained "
                 "by the two inputs separately, weighted by where the data lie). The strongest is "
                 f"{labs[top['a']].split(' (')[0]} with {labs[top['b']]}.", "fig:exp2-heart-pairs", width=r"0.95\textwidth")


