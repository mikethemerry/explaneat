def sig3(x):
    if x == 0:
        return "0"
    s = f"{x:+.2g}" if abs(x) < 0.1 else f"{x:+.2f}"
    if "e" in s:
        s = f"{x:+.4f}"
    return s.replace("-", "$-$").replace("+", "$+$")


