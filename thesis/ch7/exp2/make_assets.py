def realisation_code(r):
    import re
    if r["used"] != "True":
        return None
    if r["kind"] == "lin":
        return ""
    t = r["realisation"]
    n = r["n_parts"] or "1"
    m = re.match(r"split across (\d+) units in (\d+) part", t)
    if m:
        return f"S{m.group(1)}/{m.group(2)}p"
    if t.startswith("single hinge"):
        return f"H/{n}p"
    if t.startswith("single gate"):
        return f"G/{n}p"
    return ""


