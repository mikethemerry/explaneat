def params(p):
    def v(x):
        return "/".join(str(i) for i in x) if isinstance(x, list) else g(x) if isinstance(x, (int, float)) and float(x) == int(x) else str(x)
    return ", ".join(f"{KEYS.get(k, tx(k))}~{v(x)}" for k, x in p.items())


