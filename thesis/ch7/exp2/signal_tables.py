def table_adult():
    base = REPO / "experiments/adult_signals"
    if not (base / "signals.csv").exists():
        print("[signal tables] experiments/adult_signals/signals.csv missing: Adult table skipped")
        return
    S = rows("experiments/adult_signals/signals.csv")
    M = rows("experiments/adult_signals/matrix.csv")
    P = rows("experiments/adult_signals/projection.csv")
    idx = {(int(r["seed"]), r["signal"]): r for r in M}
    grp = lambda r: ("absent" if int(r["n_seeds_used"]) == 0 else ("lin" if r["kind"] == "lin" else "nonlin"))
    order = {"lin": 0, "nonlin": 1, "absent": 2}
    keep = [r for r in S if int(r["n_seeds_used"]) > 0 or r["data_relevant"] == "True"]
    keep.sort(key=lambda r: (order[grp(r)], -float(r["data_cv_logloss_gain"])))
    out = []
    for r in keep:
        s = r["signal"]
        cells = []
        for sd in SEEDS:
            m = idx[(sd, s)]
            if m["used"] != "True":
                cells.append("w" if float(m["sd_train"]) >= 0.03 else "")
            else:
                cells.append(tx(m["code"].split("/")[0]) if m["code"] else TICK)
        nu = int(r["n_seeds_used"])
        assert nu == sum(c not in ("", "w") for c in cells), s
        test = None
        out.append((grp(r), f"\\textbf{{{tx(r['name'])}}}: {tx(r['description'])}", cells, test, tx(r["notes"])))
    r2 = [float(p["r2_train"]) for p in P]
    r2t = [float(p["r2_test"]) for p in P]
    groups = {"lin": "Linear core (slopes and one-hot offsets), strongest in the data first",
              "nonlin": "Non-linear: bends and interactions, strongest in the data first",
              "absent": "Relevant in the data but in no network"}
    cap = ("Adult: signals (rows) by seed (columns). The positive class is an income of at most \\$50K, "
           "so a signal that raises the score makes a low income likelier. Each network's logit is "
           "projected on a basis of data functions (\\texttt{experiments/adult\\_signals}): linear terms per "
           "variable or one-hot group, bends for continuous inputs, and interactions the explanations' units "
           f"read together; the projection explains {num(min(r2), 3)} to {num(max(r2), 3)} of the logit's "
           "variance (training rows). A single one-hot switching unit counts as linear. A seed \\emph{uses} "
           "a signal when its component, clipped to its 1st to 99th percentiles, has a standard deviation of "
           "at least 0.10 logit. \\checkmark: used; H, one hinge; G, one gate; S$k$, split across $k$ units; "
           "w: weak (0.03 to 0.10 logit). Notes: routes for linear signals (edge, units) and realisation "
           "counts with explanation parts. Rows are ordered by the data's own strength (cross-validated "
           "log-loss gain in a ridge fit on the same basis).")
    write_sideways("exp2-signals-adult", cap, "tab:exp2-signals-adult", frame(out, groups))


def build():
    table_churn()
    table_heart()
    table_adult()


if __name__ == "__main__":
    build()
