"""Experiment 2: one signal table per dataset (called by make_assets.main()).

Rows are signals (a data-defined, model-independent function of the inputs, with a one-line plain
description); columns are the ten seeds and a notes column for the realisation
variants. Linear signals come first, then the non-linear ones by the data's own strength, so the
table reads as a linear core plus non-linear variations.

Sources (read-only):
    Churn      experiments/churn_signals/signals.csv, matrix.csv (catalogue.py), data/churn_shapes.json
    Heart-100  experiments/heart100_audit/linear_core.csv (linear terms), features.csv (unit rows,
               non-linear families)
    Adult      experiments/adult_signals/signals.csv, matrix.csv, projection.csv (catalogue.py)

Outputs: tables/exp2/exp2-signals-{churn,heart100,adult}.tex
"""
from __future__ import annotations

import json
import re
import statistics as st
from collections import Counter, OrderedDict, defaultdict

import numpy as np

from make_assets import (CLS_ORDER, DATA, REPO, SHORT_TERM, SIG_NAME, TAB, num, realisation_code, rows,
                         tx)

TICK = r"\checkmark"
SEEDS = range(10)


def write_sideways(name, caption, label, body):
    TAB.mkdir(parents=True, exist_ok=True)
    src = ("% Generated by thesis/ch7/exp2/signal_tables.py (via make_assets.py) -- do not edit by hand.\n"
           "\\begin{sidewaystable}\n  \\thesistablestyle\n  \\centering\n  \\footnotesize\n" + body.rstrip()
           + f"\n  \\caption{{{caption}}}\n  \\label{{{label}}}\n\\end{{sidewaystable}}\n")
    (TAB / f"{name}.tex").write_text(src)


def frame(rows_tex, groups, notes_w="4.4cm"):
    """rows_tex: list of (group, signal cell, [10 cells], unused, notes cell)."""
    head = " & ".join(f"s{s}" for s in SEEDS)
    body = ["  \\setlength{\\tabcolsep}{2.6pt}",
            f"  \\begin{{tabularx}}{{\\textheight}}{{@{{}}>{{\\raggedright\\arraybackslash}}X*{{10}}{{c}}"
            f">{{\\raggedright\\arraybackslash}}p{{{notes_w}}}@{{}}}}",
            "    \\toprule", f"    Signal & {head} & Notes (realisation) \\\\"]
    last = None
    for g, sig, cells, test, note in rows_tex:
        if g != last:
            body += ["    \\midrule", f"    \\multicolumn{{12}}{{@{{}}l}}{{\\textit{{{groups[g]}}}}} \\\\"]
            last = g
        body.append(f"    {sig} & " + " & ".join(cells) + f" & {note} \\\\")
    body += ["    \\bottomrule", "  \\end{tabularx}"]
    return "\n".join(body)


# =============================================================================== Churn

DESCRIPTIONS = REPO / "experiments/signal_descriptions/descriptions.json"


def descriptions():
    """Row descriptions, each claim checked by experiments/signal_descriptions/describe.py (which
    fills their numbers and counts from computed values)."""
    return json.loads(DESCRIPTIONS.read_text())


def churn_desc():
    """Churn row descriptions (descriptions.json). The two numbers (where the data's curve bends)
    are recomputed here from the data's own shape (data/churn_shapes.json, the ridge fit on the
    catalogue basis) and must agree with the checked texts."""
    sh = json.loads((DATA / "churn_shapes.json").read_text())
    x, y = np.array(sh["calls"]["x"]), np.array(sh["calls"]["data"])
    inc = np.diff(y)
    k = int(x[1:][np.argmax(inc >= 0.5 * inc.max())])          # first call count with a steep step
    xd, yd = np.array(sh["day"]["x"]), np.array(sh["day"]["data"])
    sd = np.diff(yd) / np.diff(xd)
    lo = xd[int(np.argmin(yd))]
    up = int(round(xd[1:][np.argmax((sd >= 0.5 * sd.max()) & (xd[1:] > lo))] / 10) * 10)
    D = descriptions()
    assert D["numbers"]["churn"] == {"k_calls": k, "up_day": up}, (D["numbers"]["churn"], k, up)
    return D["churn"], k, up


def lin_route(realisation):
    """'edge' when any of the seed's carriers is a direct input-to-output edge, else 'units'."""
    return "edge" if "direct" in realisation else "units only"


def table_churn():
    S = rows("experiments/churn_signals/signals.csv")
    M = rows("experiments/churn_signals/matrix.csv")
    idx = {(int(r["seed"]), r["signal"]): r for r in M}
    desc, k_calls, up_day = churn_desc()
    keep = [r for r in S if int(r["n_seeds_used"]) > 0 or
            (r["data_relevant"] == "True" and float(r["data_cv_logloss_gain"]) > 0.002)]
    grp = lambda r: ("absent" if int(r["n_seeds_used"]) == 0 else ("lin" if r["kind"] == "lin" else "nonlin"))
    order = {"lin": 0, "nonlin": 1, "absent": 2}
    keep.sort(key=lambda r: (order[grp(r)], -float(r["data_cv_logloss_gain"])))
    out = []
    for r in keep:
        s = r["signal"]
        name = SIG_NAME.get(s, tx(r["name"]))
        cells, notes, parts = [], Counter(), []
        for sd in SEEDS:
            m = idx[(sd, s)]
            code = realisation_code(m)
            if code is None:
                cells.append("w" if m["presence"] == "weak" else "")
                continue
            if r["kind"] == "lin":
                cells.append(TICK)
                notes[lin_route(m["realisation"])] += 1
            else:
                cells.append(code.split("/")[0] if code else TICK)
                notes[code.split("/")[0][0] if code else "other"] += 1
                if code and "/" in code:
                    parts.append(int(code.split("/")[1].rstrip("p")))
        nu = int(r["n_seeds_used"])
        assert nu == sum(c not in ("", "w") for c in cells), s
        if r["kind"] == "lin":
            note = "; ".join(f"{k} {v}" for k, v in notes.most_common())
        else:
            note = ", ".join(f"{k}{'' if k in 'HGS' else ' '}{v}" for k, v in notes.most_common())
            if parts:
                note += (f"; {min(parts)} part" if max(parts) == min(parts) == 1 else
                         f"; {min(parts)}--{max(parts)} parts" if max(parts) != min(parts) else f"; {min(parts)} parts")
        if nu == 0:
            note = f"data's CV gain {num(float(r['data_cv_logloss_gain']), 3, sign=True)}"
        test = None
        out.append((grp(r), f"\\textbf{{{name}}}: {desc.get(s, tx(r['name']))}", cells, test, note))
    from scipy.stats import spearmanr
    rho = float(spearmanr([float(r["data_cv_logloss_gain"]) for r in keep],
                          [int(r["n_seeds_used"]) for r in keep]).statistic)
    groups = {"lin": "Linear core (slopes and offsets), strongest in the data first",
              "nonlin": "Non-linear: bends and interactions, strongest in the data first",
              "absent": "Relevant in the data but in no network"}
    cap = ("Churn: signals (rows) by seed (columns). A signal is a churn-relevant function of the "
           "inputs defined on the data, not on any model; a seed \\emph{uses} it when the projection of "
           "its logit on the signal's basis functions has a standard deviation of at least 0.10 logit "
           "(training rows, after clipping to its 1st--99th percentiles; the rule of all three data sets). \\checkmark: used; for a non-linear signal the realisation instead: H, one "
           "hinge; G, one gate (a unit that also reads another input); S$k$, split across $k$ units. w: "
           "weak (0.03 to 0.10 logit). Notes: seeds carrying a linear signal on a direct "
           "input-to-output edge or only through switching units; realisation counts and explanation "
           "parts. Rows are ordered by "
           "the data's own strength (cross-validated log-loss gain in a ridge fit); strength and the number "
           f"of seeds using a signal have a Spearman correlation of {num(rho, 2)}.")
    write_sideways("exp2-signals-churn", cap, "tab:exp2-signals-churn", frame(out, groups))


