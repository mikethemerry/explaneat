"""Appendix table: Heart test AUC over 100 random splits vs the paper split (tab:heart-splits).

Reads experiments/benchmarks/heart_splits.json (heart_splits.py) and experiments/10seed/runs_heart100.csv.
    python3 thesis/ch7/appendix/heart_splits_table.py
"""
import csv, json, statistics
from pathlib import Path

REPO = Path(__file__).resolve().parents[3]
S = json.load(open(REPO / "experiments/benchmarks/heart_splits.json"))
runs = [float(r["test_auc"]) for r in csv.DictReader(open(REPO / "experiments/10seed/runs_heart100.csv"))]
NAMES = [("L2", "Logistic regr., $L_2$"), ("L1", "Logistic regr., $L_1$ (sparse)"), ("RF", "Random forest"),
         ("GB", "Gradient boosting"), ("EBM", "Explainable boosting")]

rows = []
for k, name in NAMES:
    m = S["models"][k]
    share = "--" if m["share_beats_L2"] is None else f"{round(100 * m['share_beats_L2'])}\\%"
    rows.append(f"    {name} & {m['paper_split']:.3f} & {m['mean']:.3f} & {m['sd']:.3f} & {m['p5']:.3f}--{m['p95']:.3f} & {share} \\\\")
prop = (f"    PropNEAT (median, ten seeds) & {statistics.median(runs):.3f} & -- & -- & -- & -- \\\\")

tex = r"""% Generated by thesis/ch7/appendix/heart_splits_table.py -- do not edit by hand.
\begin{table}[tbp]
  \centering
  \footnotesize
  \setlength{\tabcolsep}{4pt}
  \begin{adjustbox}{max width=\textwidth}
  \begin{tabular}{@{}lccccc@{}}
    \toprule
    & Fixed split & \multicolumn{4}{c}{100 random splits (242 / 61)} \\
    \cmidrule(l){3-6}
    Model & test AUC & mean & SD & 5th--95th pct. & beats $L_2$ LR \\
    \midrule
""" + "\n".join(rows) + r"""
    \midrule
""" + prop + r"""
    \bottomrule
  \end{tabular}
  \end{adjustbox}
  \caption{Heart: test AUC on the fixed split against 100 random stratified splits of the same 303 patients into 242 training and 61 test rows (\texttt{StratifiedShuffleSplit}, seed 1). }
  \label{tab:heart-splits}
\end{table}
"""
out = Path(__file__).parent / "tables/ch7-heart-splits.tex"
out.write_text(tex)
print("wrote", out)
