"""Grid-boundary check of every CV choice in the comparator suite (run by make_csv.py; also standalone).

    uv run python experiments/benchmarks/check_grids.py

Reads results/classification/*.json and results/survival.json. For every tuned parameter of every model
and dataset, the chosen value's place in its grid: interior, at the end of the parameter's range
(common.DOMAIN_ENDS, e.g. max_depth None or min_samples_leaf 1: the grid cannot be widened there), or at
a grid edge. Writes results/grid_check.md (generated; every choice) and exits non-zero if any choice is
at a grid edge.
"""
from __future__ import annotations

import json
import sys

from common import DOMAIN_ENDS, RESULTS, jload
from search import edge_hits


def fmt(v):
    return json.dumps(v)


def results():
    for f in sorted((RESULTS / "classification").glob("*.json")):
        if f.stem == "xor":
            continue
        for m, r in jload(f)[f.stem].items():
            yield f.stem, m, r
    for ds, res in jload(RESULTS / "survival.json").items():
        for m, r in res.items():
            if isinstance(r, dict) and "stages" in r:
                yield ds, m, r


def check():
    lines = ["# Grid check (generated by experiments/benchmarks/check_grids.py)", "",
             "Every CV choice of the comparator suite and its place in its grid. `interior`: neither end; "
             "`range end`: the end of the parameter's range (common.DOMAIN_ENDS; for the EBM also "
             "classification.range_ends: all feature pairs, or more bins than any feature has values), where the "
             "grid cannot be widened; `tie`: at a grid end, but a combination of the stage's grid with an interior value of the parameter has exactly the same CV score, so the optimum is not at the edge (search.interior_tie); `re-tuned`: a later stage tunes the parameter again and decides its final value; `EDGE`: at an end of the grid that could be widened.", "",
             "| dataset | model | stage | parameter | chosen | position | grid | status |",
             "|---|---|---|---|---|---|---|---|"]
    edges = []
    for ds, m, r in results():
        last = {k: i for i, st in enumerate(r["stages"], start=1) for k in st["grid"]}
        for i, st in enumerate(r["stages"], start=1):
            ends = {k: DOMAIN_ENDS.get(k, []) + v for k, v in r.get("range_ends", {}).items() if isinstance(v, list)}
            ends = {**DOMAIN_ENDS, **ends}
            hits = {k for k, _, _ in edge_hits([st], ends)}
            hits = {k for k in hits if last[k] == i}
            for k, vals in st["grid"].items():
                if len(vals) < 2:
                    continue
                v = st["chosen"][k]
                pos = vals.index(v) + 1
                at_end = pos in (1, len(vals))
                status = "EDGE" if k in hits else ("range end" if at_end else "interior")
                if status == "range end" and v not in ends.get(k, []) and k != "hidden_layer_sizes":
                    status = "tie: an interior value scores the same"
                if k == "hidden_layer_sizes" and k not in hits:   # widths ordered within a depth (search.edge_hits)
                    status = "range end" if pos == 1 else "interior"
                if last[k] != i:
                    status = "re-tuned in stage %d" % last[k]
                if status == "EDGE":
                    edges.append((ds, m, k, v))
                lines.append(f"| {ds} | {m} | {i} | {k} | {fmt(v)} | {pos} of {len(vals)} | "
                             f"{fmt(vals[0])} .. {fmt(vals[-1])} | {status} |")
    lines += ["", f"Choices at a grid edge: {len(edges)}."]
    (RESULTS / "grid_check.md").write_text("\n".join(lines) + "\n")
    return edges


def main():
    edges = check()
    for e in edges:
        print("EDGE", *e)
    print(len(edges), "choices at a grid edge ->", RESULTS / "grid_check.md")
    if edges:
        sys.exit(1)


if __name__ == "__main__":
    main()
