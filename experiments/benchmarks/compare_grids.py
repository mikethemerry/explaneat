"""Before / after the grid widening of 21 Nov 2026: every comparator, the best comparator per dataset, and
every PropNEAT-versus-comparator relation that flips.

    uv run python experiments/benchmarks/compare_grids.py

Reads results/narrow_grids/benchmarks.csv and results/narrow_grids/heart_splits.json (the first run, on
the grids of experiments/references) and benchmarks.csv and heart_splits.json (this run), and, for the
synthetic sets' true-logit AUC, experiments/ushape_saddle/references.json. Writes
results/before_after.csv (one row per dataset and comparator) and results/before_after.md (generated).
Gap closed: (PropNEAT - LR) / (reference - LR), LR the L2 logistic regression of the suite, reference
gradient boosting or the true logit (synthetic sets).
"""
from __future__ import annotations

import csv
import json

from common import HERE, REPO, RESULTS

NARROW = RESULTS / "narrow_grids"
PROPNEAT = ["propneat_explained", "propneat_selected", "propneat_best_by_train", "propneat_median10"]
COMP = ["lr_l2", "lr_l1", "tree", "rf", "gb", "ebm", "mlp", "cox_ph", "cox_l2", "cox_enet", "rsf", "gbs"]
SYN = {"shape_u": "u", "shape_saddle": "saddle", "shape_both": "both"}


def load(path):
    with open(path) as f:
        return {(r["dataset"], r["model_key"]): r for r in csv.DictReader(f) if r["test_value"] != ""}


def f4(x):
    return f"{x:.4f}"


def main():
    B, A = load(NARROW / "benchmarks.csv"), load(HERE / "benchmarks.csv")
    sets = list(dict.fromkeys(d for d, _ in A if d != "xor"))
    rows, md = [], ["# Before / after the grid widening (generated by experiments/benchmarks/compare_grids.py)", "",
                    "Before: results/narrow_grids/ (the grids of experiments/references, 19 Nov 2026). After: this "
                    "suite's grids (classification.py, survival.py). Test AUC (survival: Harrell's C).", "",
                    "## Every comparator", "",
                    "| dataset | model | before | after | change | settings before | settings after |",
                    "|---|---|---|---|---|---|---|"]
    for d in sets:
        for m in COMP:
            if (d, m) not in A:
                continue
            b, a = float(B[(d, m)]["test_value"]), float(A[(d, m)]["test_value"])
            rows.append({"dataset": d, "model": m, "before": b, "after": a, "change": a - b,
                         "cv_before": B[(d, m)]["cv_score"], "cv_after": A[(d, m)]["cv_score"],
                         "params_before": B[(d, m)]["params"], "params_after": A[(d, m)]["params"]})
            md.append(f"| {d} | {m} | {f4(b)} | {f4(a)} | {a - b:+.4f} | `{B[(d, m)]['params']}` | `{A[(d, m)]['params']}` |")
    with open(RESULTS / "before_after.csv", "w", newline="") as f:
        w = csv.DictWriter(f, fieldnames=list(rows[0]))
        w.writeheader()
        w.writerows(rows)

    md += ["", "## Best comparator per dataset", "", "| dataset | before | after |", "|---|---|---|"]
    best = {}
    for d in sets:
        out = []
        for K in (B, A):
            k = max((m for m in COMP if (d, m) in K), key=lambda m: float(K[(d, m)]["test_value"]))
            out.append((k, float(K[(d, k)]["test_value"])))
        best[d] = out
        md.append(f"| {d} | {out[0][0]} {f4(out[0][1])} | {out[1][0]} {f4(out[1][1])} |")

    md += ["", "## PropNEAT against each comparator: relations that flip", "",
           "PropNEAT's row (explained network; Experiment 2: best seed by training AUC and median of ten) minus "
           "each comparator, before and after; listed when the sign changes (full precision) or when the order "
           "at three decimals changes.", "",
           "| dataset | PropNEAT row | comparator | before | after |", "|---|---|---|---|---|"]
    flips = 0
    for d in sets:
        for p in PROPNEAT:
            if (d, p) not in A:
                continue
            pv = float(A[(d, p)]["test_value"])
            for m in COMP:
                if (d, m) not in A:
                    continue
                db, da = pv - float(B[(d, m)]["test_value"]), pv - float(A[(d, m)]["test_value"])
                r3 = lambda x: round(x, 3)  # noqa: E731
                s3b = (r3(pv) > r3(float(B[(d, m)]["test_value"]))) - (r3(pv) < r3(float(B[(d, m)]["test_value"])))
                s3a = (r3(pv) > r3(float(A[(d, m)]["test_value"]))) - (r3(pv) < r3(float(A[(d, m)]["test_value"])))
                if (db > 0) != (da > 0) or s3b != s3a:
                    flips += 1
                    md.append(f"| {d} | {p} | {m} | {db:+.4f} | {da:+.4f} |")
    md += ["", f"Relations that flip: {flips}.", "", "## PropNEAT against the best comparator", "",
           "| dataset | PropNEAT row | PropNEAT | minus best before | minus best after |", "|---|---|---|---|---|"]
    for d in sets:
        for p in PROPNEAT:
            if (d, p) in A:
                pv = float(A[(d, p)]["test_value"])
                md.append(f"| {d} | {p} | {f4(pv)} | {pv - best[d][0][1]:+.4f} ({best[d][0][0]}) | "
                          f"{pv - best[d][1][1]:+.4f} ({best[d][1][0]}) |")

    ref = json.loads((REPO / "experiments/ushape_saddle/references.json").read_text())
    md += ["", "## Gap closed", "", "(PropNEAT - LR) / (reference - LR); LR and GB from the suite.", "",
           "| dataset | PropNEAT row | reference | before | after |", "|---|---|---|---|---|"]
    for d in sets:
        for p in PROPNEAT:
            if (d, p) not in A or (d, "lr_l2") not in A or (d, "gb") not in A:
                continue
            pv = float(A[(d, p)]["test_value"])
            refs = [("GB", float(B[(d, "gb")]["test_value"]), float(A[(d, "gb")]["test_value"]))]
            if d in SYN:
                o = ref[SYN[d]]["oracle"]["test_auc"]
                refs.append(("true logit", o, o))
            lb, la = float(B[(d, "lr_l2")]["test_value"]), float(A[(d, "lr_l2")]["test_value"])
            for name, rb, ra in refs:
                md.append(f"| {d} | {p} | {name} | {(pv - lb) / (rb - lb):.0%} | {(pv - la) / (ra - la):.0%} |")

    hb = json.loads((NARROW / "heart_splits.json").read_text())["models"]
    ha = json.loads((HERE / "heart_splits.json").read_text())["models"]
    md += ["", "## Heart, 100 random splits", "",
           "| model | fixed split before | fixed split after | mean before | mean after | sd before | sd after | "
           "beats L2 before | beats L2 after |", "|---|---|---|---|---|---|---|---|---|"]
    for k in ha:
        sb, sa = hb[k]["share_beats_L2"], ha[k]["share_beats_L2"]
        md.append(f"| {k} | {hb[k]['paper_split']:.3f} | {ha[k]['paper_split']:.3f} | {hb[k]['mean']:.3f} | "
                  f"{ha[k]['mean']:.3f} | {hb[k]['sd']:.3f} | {ha[k]['sd']:.3f} | "
                  f"{'--' if sb is None else f'{sb:.2f}'} | {'--' if sa is None else f'{sa:.2f}'} |")
    (RESULTS / "before_after.md").write_text("\n".join(md) + "\n")
    print("\n".join(md))


if __name__ == "__main__":
    main()
