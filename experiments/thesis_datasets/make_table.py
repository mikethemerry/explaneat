def _float(env, rows_, spec, width, caption, label):
    lines = [
        f"\\begin{{{env}}}" + ("[tbp]" if env == "table" else ""),
        "  \\thesistablestyle",
        "  \\centering",
        "  \\scriptsize",
        "  \\setlength{\\tabcolsep}{1.5pt}",
        "  \\renewcommand{\\arraystretch}{1.1}",
        f"  \\begin{{adjustbox}}{{max width={width}}}",
        "  \\begin{tabular}{" + spec + "}",
        "    \\toprule",
        "   " + GROUP[0],
        "    " + GROUP[1],
        "    " + " & ".join(HEAD) + " \\\\",
        "    \\midrule",
    ]
    lines += ["    " + r for r in rows_]
    lines += [
        "    \\bottomrule",
        "  \\end{tabular}",
        "  \\end{adjustbox}",
        f"  \\caption{{{caption}}}",
        f"  \\label{{{label}}}",
        f"\\end{{{env}}}",
    ]
    return lines


def tex(tab_rows, img_rows):
    spec = ("@{}" + P("2.0cm") + "rrr" + P("1.45cm") + P("2.3cm") + P("6.0cm") + P("3.4cm") + P("3.3cm")
            + "c@{}")
    spec_img = ("@{}" + P("1.75cm") + "rrr" + P("1.3cm") + P("1.75cm") + P("2.8cm") + P("1.75cm") + P("3.2cm")
                + "c@{}")
    lines = ["% Generated by experiments/thesis_datasets/make_table.py -- do not edit by hand.",
             "% Two floats: the tabular datasets (landscape) and the MNIST datasets."]
    lines += _float("sidewaystable", tab_rows, spec, "\\textheight", CAPTION, "tab:ch7-datasets")
    lines += [""]
    lines += _float("table", img_rows, spec_img, "\\textwidth", CAPTION_MNIST, "tab:ch7-datasets-mnist")
    return "\n".join(lines) + "\n"


def main():
    csv_rows, tab_rows, img_rows = build()
    buf = io.StringIO()
