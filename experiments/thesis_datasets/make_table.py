def ph(key, **kw):
    t, p = PHRASE[key]
    return t.format(**kw), p.format(**kw)


def n(x):
    return f"{x:,}"


def plural(k, word):
    return f"{k} {word}" if k == 1 else f"{k} {word}s"


def outcome_label(key):
    """Outcome label -- curated, each asserted against the stored record."""
    if key in S:
        ev = S[key]["event_field"]
        lab = {"fstat": "death", "cens": "recurrence or death"}[ev]
        return f"{lab}, \\texttt{{{ev}}}; Cox survival", lab + f", {ev}; Cox survival"
    if key == "xor":
        return "$x_1 \\neq x_2$", "x1 != x2"
    if key in MNIST10:
        assert M[key]["n_classes"] == 10
        return "digit 0--9, 10 classes", "digit 0-9, 10 classes"
    r = C[key]
    ds, cn = r["dataset"], r["dataset"]["class_names"]
    if key == "adult":
        assert cn[1] == "<=50k", cn
        return "income $\\le$ \\$50K", "income <= 50K"
    if key == "heart":
        assert r["parent"]["target_rule"] == "parent > 0" and len(r["parent"]["class_names"]) == 5
        return "disease, \\texttt{num} $>$ 0 of 5 levels", "disease, num > 0 of 5 levels"
    if key == "monk2":
        assert cn[1].startswith("1: exactly two"), cn
        return "exactly two $a_i = 1$", "exactly two a_i = 1"
    if key == "churn":
        assert cn[1] == "1: churned", cn
        return "churned", "churned"
    if key.startswith("c4_"):
        assert ds["target_description"].startswith("1 = x (first player, to move) wins"), ds["target_description"]
        assert ds["target_description"].endswith("0 = loss or draw")
        return "first player wins, vs.\\ loss or draw", "first player wins, vs. loss or draw"
    if key.startswith("shape_"):
        assert ds["target_description"] == "1 = outcome, 0 = no outcome"
        return "outcome", "outcome"
    raise KeyError(key)


def source(key):
    if key in S:
        return "scikit-survival"
    if key == "xor":
        return "synthetic"
    if key in M:
        return "OpenML"
    r = C[key]
    src = (r.get("parent") or r["dataset"])["source"]
    return {"PMLB (derived)": "PMLB"}.get(src, src)


def task(key, tex=False):
    if key in S:
        return "Cox survival" if tex else "survival (Cox)"
    if key in M:
        return f"{len(M[key]['train_class_counts'])}-class"
    return "binary"


def pct(x):
    return f"{100 * x:.1f}\\%", f"{x:.6f}"


def share(key):
    """(LaTeX, plain) training share of the outcome / event / classes."""
    if key in M:
        sh = M[key]["train_class_shares"]
        lo, hi = min(sh), max(sh)
        if f"{100 * lo:.1f}" == f"{100 * hi:.1f}":
            return f"{100 * lo:.1f}\\% each", f"{lo:.6f} each"
        return f"{100 * lo:.1f}--{100 * hi:.1f}\\% each", f"{lo:.6f}-{hi:.6f} each"
    if key in S:
        return pct(S[key]["event_rate_train"])
    if key == "xor":
        return pct(D["xor"]["positive"])
    return pct(C[key]["positive_train"])


def _classification_steps(key):
    """Steps in the order they were applied: row / column removal, imputation, encoding, scaling."""
    r = C[key]
    assert r["split"]["scaler_type"] == "StandardScaler" and r["split"]["scaler_fit_rows"] == "train", key
    steps = []
    p = r.get("parent")
    if key == "monk2":
        card = p["additional_metadata"]["attribute_cardinalities"]
        full = 1
        for v in card.values():
            full *= v
        assert r["n_rows"] == r["n_unique_input_rows"] == full, key
        steps.append(ph("dedup", n=n(full)))
    if p and p["dropped"]:
        steps.append(ph("removed", what=" and ".join(p["dropped"])))
    if p and p["imputed"]:
        imp = p["imputed"]
        lv = p.get("imputed_levels") or {}
        own = {k.split(":")[0]: k for k in lv}   # one-hot columns made of the imputed value
        tex_items, plain_items = [], []
        for c in sorted(imp):
            assert c not in own or lv[own[c]] == imp[c]["rows"], c
            k = imp[c]["rows"]
            tex_items.append(f"\\texttt{{{c}}}: {plural(k, 'value')}"
                             + (f", one-hot encoded as their own column \\texttt{{{own[c]}}}" if c in own else ""))
            plain_items.append(f"{c}: {plural(k, 'value')}"
                               + (f", one-hot encoded as their own column {own[c]}" if c in own else ""))
        t, _ = ph("mean_impute", n=n(r["n_rows"]), items="; ".join(tex_items))
        _, pl = ph("mean_impute", n=n(r["n_rows"]), items="; ".join(plain_items))
        steps.append((t, pl))
    enc = r["dataset"]["encoding_config"] or {}
    cat = enc.get("categorical") or {}
    if cat:
        cols = sum(len(v) for v in cat.values())
        assert r["n_inputs"] == cols + len(enc.get("passthrough", {})), key
        assert not enc.get("ordinal_as_onehot") and not enc.get("ordinal_as_ranked"), key
        if key == "churn":
            what = " and ".join(sorted(cat, key=lambda c: p["feature_names"].index(c)))
        elif p and len(cat) == p["n_inputs"]:
            what = f"all {len(cat)} attributes"
        else:
            what = f"{len(cat)} categorical attributes"
        steps.append(ph("onehot", what=what, cols=cols))
        if key == "adult":
            for c, k in ADULT_UCI_LEVELS.items():
                assert len(cat[c]) == k + 1, (c, len(cat[c]))
            steps.append(ph("unknown_level", cols=", ".join(ADULT_UCI_LEVELS)))
        binary = [c for c, t in enc.get("passthrough", {}).items() if t == "binary"]
        if binary:
            what = (f"binary attribute {binary[0]}" if len(binary) == 1
                    else f"{len(binary)} binary attributes ({', '.join(binary)})")
            steps.append(ph("binary", what=what, s="" if len(binary) == 1 else " each"))
    if key == "c4_cells":
        assert r["dataset"]["additional_metadata"]["encoding"].startswith("ordinal per cell: x = +1, o = -1, blank = 0")
        steps.append(ph("c4_cells", n=r["n_inputs"]))
    if key == "c4_lines":
        md = r["dataset"]["additional_metadata"]
        assert md["n_inputs"] == r["n_inputs"] == len(md["codebook"])
        assert md["base_dataset"] == C["c4_cells"]["dataset"]["name"]
        steps.append(ph("c4_lines", n=r["n_inputs"]))
    if key.startswith("shape_"):
        assert r["split"]["preprocessing_steps"][0] == "raw units"
        steps.append(ph("natural_units"))
    steps.append(ph("zscore"))
    return steps


def _survival_steps(key):
    s = S[key]
    cat = s["categorical"]
    levels = s["categorical_levels"]
    cols = sum(v - 1 for v in levels.values())
    assert s["n_inputs"] == s["n_inputs_raw"] - len(cat) + cols
    assert s["missing_cells"] == 0 and s["scaler_fit_rows"] == "train"
    if all(v == 2 for v in levels.values()):
        what = f"{len(cat)} two-level categorical attributes"
    else:
        what = f"{len(cat)} categorical attributes"
    return [ph("onehot_drop", what=what, cols=cols), ph("zscore")]


def _mnist_steps(key):
    m = M[key]
    assert key in MNIST10 and m["n_classes"] == 10, key
    return [ph("pixels", max=M["source"]["pixel_max_raw"])]


def preprocessing(key):
    """((LaTeX, plain) of the steps before scaling, joined by '; ' in the order they were applied,
    (LaTeX, plain) of the input scaling, the last step)."""
    if key == "xor":
        steps = [ph("none"), ph("noscale")]
    elif key in S:
        steps = _survival_steps(key)
    elif key in M:
        steps = _mnist_steps(key)
        if len(steps) == 1:
            steps.insert(0, ph("none_pixels", max=M["source"]["pixel_max_raw"]))
    else:
        steps = _classification_steps(key)
    *before, (s_tex, s_plain) = steps
    tex = "; ".join(t for t, _ in before)
    plain = "; ".join(p for _, p in before)
    up = lambda x: x[0].upper() + x[1:]  # noqa: E731
    return (up(tex), up(plain)), (up(s_tex), up(s_plain))


def inputs(key):
    """(LaTeX, raw count, model inputs as text)."""
    if key in M:
        src = M["source"]
        h, w = src["image_hw"]
        assert h * w == src["n_pixels"]
        return (f"{src['n_pixels']} pixels $\\to$ one {h}$\\times${w} map", src["n_pixels"],
                f"one {h}x{w} map")
    if key in S:
        raw, enc = S[key]["n_inputs_raw"], S[key]["n_inputs"]
    elif key == "xor":
        raw = enc = D["xor"]["n_inputs"]
    else:
        r = C[key]
        enc = r["n_inputs"]
        if r.get("parent"):
            raw = r["parent"]["n_inputs"] + len(r["parent"]["dropped"])
        elif key == "c4_lines":
            raw = C["c4_cells"]["n_inputs"]
        else:
            raw = enc
    return f"{raw} $\\to$ {enc}", raw, str(enc)


def rows(key):
    """(train, val, test, val note) -- val note: Experiment 3 early-stopping rows held out of train."""
    if key in S:
        s = S[key]
        return s["n_train"], s["n_val"], s["n_test"], None
    if key in M:
        m = M[key]
        return m["n_train"], m["n_val"], m["n_test"], None
    if key == "xor":
        return D["xor"]["n_rows"], None, None, None
    r = C[key]
    assert r["n_val"] == 0
    e3 = D["exp3_validation"].get(key)
    return r["n_train"], (e3["n_val"] if e3 else None), r["n_test"], ("exp3" if e3 else None)


def split(key):
    """(LaTeX, plain, ratio, stratified, seed)."""
    if key == "xor":
        t, p = SPLIT["none"]
        return t.format(n=D["xor"]["n_rows"]), p.format(n=D["xor"]["n_rows"]), "none", "", ""
    if key in S:
        s = S[key]
        te, va = s["test_size"], s["val_size"]
        tr = (1 - te) * (1 - va)
        ratio = ":".join(str(round(100 * v)) for v in (tr, (1 - te) * va, te))
        t, p = SPLIT["event"]
        kw = dict(ratio=ratio, te=round(100 * te), va=round(100 * va), seed=s["seed"])
        return t.format(**kw), p.format(**kw), ratio, "event", s["seed"]
    if key in MNIST10:
        m = M[key]
        std = M["source"]["n_standard_train"]
        assert m["n_test"] == M["source"]["n_standard_test"] and m["pool_after_val"] == std - m["n_val"]
        sub = "mnist10_all" if m["train_is_whole_pool"] else "mnist10_sub"
        tt, tp = SPLIT[sub]
        kw = dict(n=n(m["n_train"]), pool=n(m["pool_after_val"]), seed=m["split_seed"])
        t, p = SPLIT["mnist10"]
        kw2 = dict(va=n(m["n_val"]), std=n(std), seed=m["split_seed"])
        return (t.format(train=tt.format(**kw), **kw2), p.format(train=tp.format(**kw), **kw2),
                "standard test; validation from standard train", "digit", m["split_seed"])
    sp = C[key]["split"]
    te = sp["test_size"]
    ratio = f"{round(100 * (1 - te))}:{round(100 * te)}"
    t, p = SPLIT["strat" if sp["stratify"] else "random"]
    kw = dict(ratio=ratio, seed=sp["random_state"])
    return t.format(**kw), p.format(**kw), ratio, "outcome" if sp["stratify"] else "no", sp["random_state"]


def url(key):
    if key in S:
        return f"bundled with scikit-survival {S[key]['sksurv_version']} (no URL)"
    if key == "xor":
        return D["xor"]["source"]
    if key in M:
        return OPENML_URL
    r = C[key]
    return (r.get("parent") or r["dataset"])["source_url"] or ""


def build():
    """CSV rows (all datasets) and LaTeX rows: (tabular datasets, MNIST datasets)."""
    csv_rows, tab_rows, img_rows = [], [], []
    for key, name, used in ROWS:
        used = used_in(key, used)
        tr, va, te, note = rows(key)
        out_tex, out_plain = outcome_label(key)
        sh_tex, sh_plain = share(key)
        (pre_tex, pre_plain), (sc_tex, sc_plain) = preprocessing(key)
        sp_tex, sp_plain, ratio, strat, seed = split(key)
        in_tex, in_raw, in_enc = inputs(key)
        va_tex = "--" if va is None else n(va) + ("$^a$" if note else "")
        te_tex = "--" if te is None else n(te)
        (img_rows if key in M else tab_rows).append(" & ".join([
            f"{name} ({source(key)})", n(tr), va_tex, te_tex, in_tex,
            f"{out_tex} ({sh_tex})", pre_tex, sc_tex, sp_tex[0].upper() + sp_tex[1:], used]) + " \\\\")
        csv_rows.append({
            "dataset": name.replace("$+$", "+"), "key": key, "source": source(key), "citation_key": "",
            "loader": LOADER.get(key, S.get(key, {}).get("loader", "")), "url": url(key),
            "database": C[key]["database"] if key in C else "",
            "split_id": C[key]["split_id"] if key in C else "",
            "split_file": (S[key]["split_file"] if key in S else
                           "; ".join(M[key]["config_files"]) if key in MNIST10 else
                           M[key]["run_record"] if key in M else ""),
            "task": task(key), "n_train": tr, "n_val": "" if va is None else va,
            "n_val_note": "Experiment 3 early stopping, held out of the training rows" if note else "",
            "n_test": "" if te is None else te,
            "inputs_raw": in_raw, "inputs_encoded": in_enc,
            "outcome": out_plain, "share_train": sh_plain,
            "preprocessing": pre_plain, "scaling": sc_plain,
            "split": sp_plain[0].upper() + sp_plain[1:], "split_ratio": ratio,
            "stratified": strat, "split_seed": seed, "used_in": used,
        })
    return csv_rows, tab_rows, img_rows


