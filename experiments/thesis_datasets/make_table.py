"""Chapter 7 datasets table (layer 3: reads data.json only; no database).

    uv run python experiments/thesis_datasets/make_table.py     # -> datasets.csv, ch7-datasets.tex

Every number comes from ``data.json`` (written by ``extract.py`` from the database splits, loaders,
split files and run records the runs used). What is typed here are names and wording, not results:
the row order and short names, the one-word outcome labels (each checked against the stored class
names or target description), the loader each dataset was fetched with, and which experiment
reports each dataset ("used in", read off the Chapter 7 tables: Experiment 1 = the networks and
benchmark tables, Experiment 2 = the ten-seed benchmark table, Experiment 3 = the grafting
studies on Churn and MONK-2). These are marked "curated" in thesis/ch7/PROVENANCE.md.
"""
from __future__ import annotations

import csv
import io
import json
from pathlib import Path

HERE = Path(__file__).resolve().parent
D = json.loads((HERE / "data.json").read_text())
C, S = D["classification"], D["survival"]

# key -> (short name as in the Chapter 7 tables, used in) -- curated
ROWS = [
    ("adult", "Adult", "2"),
    ("heart", "Heart", "1, 2"),
    ("monk2", "MONK-2", "1, 3"),
    ("churn", "Churn", "2, 3"),
    ("whas500", "WHAS500", "1"),
    ("gbsg2", "GBSG2", "1"),
    ("c4_cells", "Connect-4, cells", "1"),
    ("c4_lines", "Connect-4, lines", "1"),
    ("xor", "XOR", "1"),
    ("shape_u", "Synthetic U", "1"),
    ("shape_saddle", "Synthetic saddle", "1"),
    ("shape_both", "Synthetic U $+$ saddle", "1"),
]

# loader the data were fetched with -- curated (the URL itself is read from the database record)
LOADER = {
    "adult": "PMLB via explaneat/db/pmlb_loader.py",
    "heart": "UCI id 45 via ucimlrepo.fetch_ucirepo (explaneat/api/routes/datasets.py; NaN -> column mean)",
    "monk2": "PMLB monk2.tsv.gz, deduplicated (dataset record monk2_dedup432)",
    "churn": "PMLB churn.tsv.gz",
    "c4_cells": "PMLB connect_4 via pmlb.fetch_data (experiments/complex_real/data.py)",
    "c4_lines": "derived from connect4_win_ordinal (experiments/c4_line_features/lfdata.py)",
    "shape_u": "generated by experiments/ushape_saddle/data.py, stored by make_datasets.py",
    "shape_saddle": "generated by experiments/ushape_saddle/data.py, stored by make_datasets.py",
    "shape_both": "generated by experiments/ushape_saddle/data.py, stored by make_datasets.py",
}


def outcome_label(key):
    """One-word outcome label -- curated, each asserted against the stored record."""
    if key in S:
        ev = S[key]["event_field"]
        lab = {"fstat": "death", "cens": "recurrence or death"}[ev]
        return f"{lab} (\\texttt{{{ev}}})", lab + f" ({ev})"
    if key == "xor":
        return "$x_1 \\neq x_2$", "x1 != x2"
    r = C[key]
    ds, cn = r["dataset"], r["dataset"]["class_names"]
    if key == "adult":
        assert cn[1] == "<=50k", cn
        return "income $\\le$ \\$50K", "income <= 50K"
    if key == "heart":
        assert r["parent"]["target_rule"] == "parent > 0" and len(r["parent"]["class_names"]) == 5
        return "disease (\\texttt{num} $>$ 0)", "disease (num > 0)"
    if key == "monk2":
        assert cn[1].startswith("1: exactly two"), cn
        return "exactly two $a_i = 1$", "exactly two a_i = 1"
    if key == "churn":
        assert cn[1] == "1: churned", cn
        return "churned", "churned"
    if key.startswith("c4_"):
        assert ds["target_description"].startswith("1 = x (first player, to move) wins"), ds["target_description"]
        assert ds["target_description"].endswith("0 = loss or draw")
        return "first player wins (vs.\\ loss, draw)", "first player wins (0 = loss or draw)"
    if key.startswith("shape_"):
        assert ds["target_description"] == "1 = outcome, 0 = no outcome"
        return "outcome", "outcome"
    raise KeyError(key)


def source(key):
    if key in S:
        return "scikit-survival"
    if key == "xor":
        return "synthetic"
    r = C[key]
    src = (r.get("parent") or r["dataset"])["source"]
    return {"PMLB (derived)": "PMLB"}.get(src, src)


def task(key, tex=False):
    if key in S:
        return "Cox" if tex else "survival (Cox)"
    return "binary"


def n(x):
    return f"{x:,}"


def pct(x):
    return f"{100 * x:.1f}\\%", f"{x:.6f}"


def preprocessing(key):
    """(LaTeX, plain) description built from the stored encoding config / steps / loader output."""
    if key == "xor":
        return "--", "none"
    if key in S:
        s = S[key]
        cat = s["categorical"]
        assert s["n_inputs"] == s["n_inputs_raw"] - len(cat) + sum(v - 1 for v in s["categorical_levels"].values())
        assert s["missing_cells"] == 0 and s["scaler_fit_rows"] == "train"
        binary = all(v == 2 for v in s["categorical_levels"].values())
        what = f"{len(cat)} binary categorical as 0/1" if binary else f"{len(cat)} categorical one-hot, first level dropped"
        return f"{what}; z", f"{what}; z-scored on training rows"
    r = C[key]
    assert r["split"]["scaler_type"] == "StandardScaler" and r["split"]["scaler_fit_rows"] == "train", key
    parts, plain = [], []
    p = r.get("parent")
    if p and p["dropped"]:
        parts.append(", ".join(p["dropped"]) + " removed")
        plain.append(parts[-1])
    enc = (r["dataset"]["encoding_config"] or {}).get("categorical")
    if enc:
        cols = list(enc)
        n_cols = sum(len(v) for v in enc.values())
        assert r["n_inputs"] == n_cols + len(r["dataset"]["encoding_config"].get("passthrough", {})), key
        if key == "churn":
            parts.append(" and ".join(cols) + " one-hot")
        elif p and len(cols) == p["n_inputs"]:
            parts.append(f"all {len(cols)} attributes one-hot")
        else:
            parts.append(f"{len(cols)} categorical one-hot ({n_cols} columns)")
        plain.append(parts[-1])
    if p and p["imputed"]:
        imp = p["imputed"]
        cols = sorted(imp)
        lv = p.get("imputed_levels") or {}
        own = {k.split(":")[0]: k for k in lv}   # one-hot columns made of the imputed value
        tex_items, plain_items = [], []
        for c in cols:
            assert c not in own or lv[own[c]] == imp[c]["rows"], c
            tail = ", own level" if c in own else ""
            tex_items.append(f"\\texttt{{{c}}} ({imp[c]['rows']}{tail})")
            plain_items.append(f"{c} ({imp[c]['rows']}{', own one-hot level ' + own[c] if c in own else ''})")
        parts.append("missing " + ", ".join(tex_items) + " set to the column mean")
        plain.append("missing " + ", ".join(plain_items) + " set to the column mean")
    if key == "monk2":
        card = p["additional_metadata"]["attribute_cardinalities"]
        full = 1
        for v in card.values():
            full *= v
        assert r["n_rows"] == r["n_unique_input_rows"] == full, key
        parts.insert(0, f"duplicates removed: each of the {n(full)} configurations once")
        plain.insert(0, parts[0])
    if key == "c4_cells":
        assert r["dataset"]["additional_metadata"]["encoding"].startswith("ordinal per cell: x = +1, o = -1, blank = 0")
        parts.append("cell $x = +1$, $o = -1$, blank $= 0$")
        plain.append("cell x = +1, o = -1, blank = 0")
    if key == "c4_lines":
        md = r["dataset"]["additional_metadata"]
        assert md["n_inputs"] == r["n_inputs"] == len(md["codebook"])
        parts.append(f"{r['n_inputs']} line and threat counts from the cells")
        plain.append(parts[-1])
    if key.startswith("shape_"):
        assert r["split"]["preprocessing_steps"][0] == "raw units"
    parts.append("z")
    plain.append("z-scored on training rows")
    return "; ".join(parts), "; ".join(plain)


def inputs_raw(key):
    if key in S:
        return S[key]["n_inputs_raw"]
    if key == "xor":
        return D["xor"]["n_inputs"]
    r = C[key]
    if r.get("parent"):
        return r["parent"]["n_inputs"] + len(r["parent"]["dropped"])
    if key == "c4_lines":
        return C["c4_cells"]["n_inputs"] if r["dataset"]["additional_metadata"]["base_dataset"] == \
            C["c4_cells"]["dataset"]["name"] else None
    return r["n_inputs"]


def inputs(key):
    if key in S:
        return S[key]["n_inputs"]
    if key == "xor":
        return D["xor"]["n_inputs"]
    return C[key]["n_inputs"]


def rows(key):
    """(train, val, test, val note) -- val note: Experiment 3 early-stopping rows held out of train."""
    if key in S:
        s = S[key]
        return s["n_train"], s["n_val"], s["n_test"], None
    if key == "xor":
        return D["xor"]["n_rows"], None, None, None
    r = C[key]
    assert r["n_val"] == 0
    e3 = D["exp3_validation"].get(key)
    return r["n_train"], (e3["n_val"] if e3 else None), r["n_test"], ("exp3" if e3 else None)


def prevalence(key):
    if key in S:
        return S[key]["event_rate_train"]
    if key == "xor":
        return D["xor"]["positive"]
    return C[key]["positive_train"]


def split(key):
    """(LaTeX, ratio, stratified, seed)."""
    if key == "xor":
        return f"none (all {D['xor']['n_rows']} rows)", "none", "", ""
    if key in S:
        s = S[key]
        te, va = s["test_size"], s["val_size"]
        tr = (1 - te) * (1 - va)
        ratio = ":".join(str(round(100 * v)) for v in (tr, (1 - te) * va, te))
        return f"{ratio}, strat.\\ (event), seed {s['seed']}", ratio, "event", s["seed"]
    sp = C[key]["split"]
    te = sp["test_size"]
    ratio = f"{round(100 * (1 - te))}:{round(100 * te)}"
    st = "strat., " if sp["stratify"] else ""
    return f"{ratio}, {st}seed {sp['random_state']}", ratio, "outcome" if sp["stratify"] else "no", sp["random_state"]


def url(key):
    if key in S:
        return f"bundled with scikit-survival {S[key]['sksurv_version']} (no URL)"
    if key == "xor":
        return D["xor"]["source"]
    r = C[key]
    return (r.get("parent") or r["dataset"])["source_url"] or ""


def build():
    csv_rows, tex_rows = [], []
    for key, name, used in ROWS:
        tr, va, te, note = rows(key)
        out_tex, out_plain = outcome_label(key)
        prev_tex, prev_plain = pct(prevalence(key))
        pre_tex, pre_plain = preprocessing(key)
        sp_tex, ratio, strat, seed = split(key)
        va_tex = "--" if va is None else n(va) + ("$^a$" if note else "")
        te_tex = "--" if te is None else n(te)
        tex_rows.append(" & ".join([
            name, source(key), task(key, tex=True), n(tr), va_tex, te_tex,
            f"{inputs_raw(key)} $\\to$ {inputs(key)}", f"{out_tex} ({prev_tex})", pre_tex, sp_tex, used]) + " \\\\")
        csv_rows.append({
            "dataset": name.replace("$+$", "+"), "key": key, "source": source(key), "citation_key": "",
            "loader": LOADER.get(key, S.get(key, {}).get("loader", "")), "url": url(key),
            "database": C[key]["database"] if key in C else "",
            "split_id": C[key]["split_id"] if key in C else "",
            "split_file": S[key]["split_file"] if key in S else "",
            "task": task(key), "n_train": tr, "n_val": "" if va is None else va,
            "n_val_note": "Experiment 3 early stopping, held out of the training rows" if note else "",
            "n_test": "" if te is None else te,
            "inputs_raw": inputs_raw(key), "inputs_encoded": inputs(key),
            "outcome": out_plain, "prevalence_train": prev_plain,
            "preprocessing": pre_plain, "split_ratio": ratio, "stratified": strat, "split_seed": seed,
            "used_in": used,
        })
    return csv_rows, tex_rows


CAPTION = ("Datasets of Chapter~7. Val.: validation. Inputs: raw features $\\to$ model inputs "
           "after encoding. Outcome: the positive class or event, with its share of the training rows. "
           "Cox: survival, Cox proportional hazards. "
           "z: standardised with the training rows' mean and SD; strat.: stratified; --: none. "
           "$^a$Experiment~3 early stopping only, held out of the training rows.")


def tex(tex_rows):
    head = ["Dataset", "Source", "Task", "Train", "Val.", "Test", "\\makecell{Inputs\\\\raw $\\to$ enc.}",
            "Outcome (training share)", "Preprocessing", "Split", "\\makecell{Used in\\\\Exp.}"]
    group = (" & & & \\multicolumn{3}{c}{Rows} & & & & & \\\\", "\\cmidrule(lr){4-6}")
    lines = [
        "% Generated by experiments/thesis_datasets/make_table.py -- do not edit by hand.",
        "\\begin{table}[tbp]",
        "  \\centering",
        "  \\footnotesize",
        "  \\setlength{\\tabcolsep}{2pt}",
        "  \\renewcommand{\\arraystretch}{1.15}",
        "  \\begin{adjustbox}{max width=\\textwidth}",
        "  \\begin{tabular}{@{}>{\\raggedright\\arraybackslash}p{1.85cm}>{\\raggedright\\arraybackslash}p{1.5cm}"
        ">{\\raggedright\\arraybackslash}p{1.0cm}rrrc"
        ">{\\raggedright\\arraybackslash}p{2.35cm}>{\\raggedright\\arraybackslash}p{3.1cm}"
        ">{\\raggedright\\arraybackslash}p{1.6cm}c@{}}",
        "    \\toprule",
        "   " + group[0],
        "    " + group[1],
        "    " + " & ".join(head) + " \\\\",
        "    \\midrule",
    ]
    lines += ["    " + r for r in tex_rows]
    lines += [
        "    \\bottomrule",
        "  \\end{tabular}",
        "  \\end{adjustbox}",
        f"  \\caption{{{CAPTION}}}",
        "  \\label{tab:ch7-datasets}",
        "\\end{table}",
    ]
    return "\n".join(lines) + "\n"


def main():
    csv_rows, tex_rows = build()
    buf = io.StringIO()
    w = csv.DictWriter(buf, fieldnames=list(csv_rows[0]), lineterminator="\n")
    w.writeheader()
    w.writerows(csv_rows)
    (HERE / "datasets.csv").write_text(buf.getvalue())
    (HERE / "ch7-datasets.tex").write_text(tex(tex_rows))
    print("wrote datasets.csv, ch7-datasets.tex")


if __name__ == "__main__":
    main()
