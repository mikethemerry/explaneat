"""Write RESULTS.md from the files completeness.py wrote (no computation beyond formatting).

    uv run python experiments/signal_completeness/report.py
"""
from __future__ import annotations

import json
from pathlib import Path

import pandas as pd

HERE = Path(__file__).resolve().parent
NAMES = {"adult": "Adult", "churn": "Churn", "heart100": "Heart-100"}

HEAD = """# Is the signal list complete? (Experiment 2, Part C)

Generated by `experiments/signal_completeness/report.py` from `summary.json`, `output_level.csv`,
`part_level.csv`, `residual_scan.csv` and `candidates.csv`. Do not edit by hand.

The tick tables check catalogue -> networks: each listed signal, is it in each network? This
folder checks the other way, networks -> catalogue: is everything the networks compute in the
list?

## Completeness criterion (fixed before running)

A data set's signal list is **complete** when

1. in every one of its ten networks, the residual logit (the logit minus its least-squares
   projection on the catalogue basis, training rows) has a standard deviation below **0.10
   logit**, measured as in the presence rule (after clipping to the 1st-99th percentiles,
   `explaneat/analysis/signal_presence.py`); and
2. the residual scan finds **no candidate signal**: no variable or variable pair whose residual
   structure is detected in two or more networks, or is detected with an SD of at least 0.10
   logit in any one network.

## Method

- **Catalogue basis.** Adult: `experiments/adult_signals/catalogue.build_basis` (linear blocks,
  bends, education levels, four interactions). Churn: `experiments/churn_signals/basis.py`.
  Heart-100: the table's rows are families of switching units, not data blocks, so each row is
  given a block of data functions from the drivers and modifiers its units read
  (`heart_basis.py`). This is a design choice of this check: the linear core plus bends in heart
  rate, blood pressure, age, ST depression and cholesterol, and interactions thallium defect x ST
  depression / slope / age, exercise angina x sex, blood pressure x (slope, heart rate, angina,
  scan), flat slope x chest pain / cholesterol / age, LV hypertrophy x (ST depression, heart
  rate), vessels x age. Non-linear blocks are residualised on the linear ones (and interactions
  on the bends), as in the catalogues.
- **(a) Output level.** Each network's logit is projected on `[1, Phi]` (least squares, training
  rows). The projection's R^2 is reported on train and, with the training coefficients, on test,
  together with the residual SD and the R^2 of the linear blocks alone.
- **(b) Part level.** Each explanation part (non-root, not a duplicate; frozen v4 records) has a
  logit contribution: the logit minus the logit with the part's exits at their baseline
  (`plain_language.build_parts`). That contribution is projected on the same basis. A part
  *maps to* a catalogue signal when that block's component of its projection is used (clipped
  SD >= 0.10 logit). Parts whose own contribution is below 0.10 are counted as small. A part
  is *unmapped* when it is used but maps to no signal.
- **(c) Residual scan.** The residual of each network is searched for structure:
  - Per data variable: out-of-fold binned means (10 quantile bins or the levels, shrunk towards 0).
  - Per variable pair: 4 x 4 cells on what is left after both one-variable effects.
  - Fit: 5-fold `KFold(shuffle, random_state=0)`.
  - Detection: the out-of-fold R^2 gain must beat the network's family-wise permutation
    threshold (the largest gain any variable or pair reaches on 19 permuted residuals,
    `RandomState(0)`), and the structure must have SD >= 0.03 logit.
  - A gradient-boosting check on all variables together (depth 3, 200 trees, the same folds,
    3 permutations; at most 10,000 fixed rows) measures how much of the residual any
    smooth model of the inputs recovers.

## Commands

```bash
DATABASE_URL=postgresql://localhost/explaneat_v4 \\
EXPLANEAT_RECORDS_DIR=experiments/10seed/explanations_v4 OMP_NUM_THREADS=1 \\
uv run python experiments/signal_completeness/load.py          # read-only DB -> cache/*.pkl (~3 min)
OMP_NUM_THREADS=1 uv run python experiments/signal_completeness/completeness.py   # ~2 min; writes the csv/json and this file
```

Deterministic: run twice, the csv, json and md outputs are byte-identical.
"""


def f3(x):
    return f"{x:.3f}"


def write():
    S = json.loads((HERE / "summary.json").read_text())
    O = pd.read_csv(HERE / "output_level.csv")
    P = pd.read_csv(HERE / "part_level.csv")
    C = pd.read_csv(HERE / "candidates.csv")
    R = pd.read_csv(HERE / "residual_scan.csv")
    L = [HEAD, "## Results by data set\n",
         "| | " + " | ".join(NAMES[d] for d in S) + " |", "|---|" + "---|" * len(S)]

    def row(label, fn):
        L.append(f"| {label} | " + " | ".join(fn(S[d]) for d in S) + " |")

    row("basis columns", lambda s: str(s["n_basis_columns"]))
    row("logit R^2, train: median (min)", lambda s: f"{f3(s['r2_train_median'])} ({f3(s['r2_train_min'])})")
    row("logit R^2, test: median (min)", lambda s: f"{f3(s['r2_test_median'])} ({f3(s['r2_test_min'])})")
    row("linear blocks alone, R^2 train (median)", lambda s: f3(s["r2_linear_train_median"]))
    row("residual SD, train: median (max)", lambda s: f"{f3(s['resid_sd_train_median'])} ({f3(s['resid_sd_train_max'])})")
    row("residual SD, test: median (max)", lambda s: f"{f3(s['resid_sd_test_median'])} ({f3(s['resid_sd_test_max'])})")
    row("networks with residual SD >= 0.10", lambda s: str(len(s["networks_resid_sd_ge_0_10"])))
    row("parts (used, SD >= 0.10)", lambda s: f"{s['n_parts']} ({s['n_parts_used']})")
    row("used parts: R^2 on the catalogue (median)", lambda s: f3(s["part_r2_train_median"]))
    row("parts mapping to no signal", lambda s: str(s["n_parts_unmapped"]))
    row("mapped parts with residual SD >= 0.10", lambda s: str(s["n_parts_mapped_with_residual"]))
    row("GB check: networks with detected residual structure", lambda s: str(s["gb_detected"]))
    row("candidate signals", lambda s: str(s["n_candidates"]))
    row("**complete by the criterion**", lambda s: "**yes**" if s["complete"] else "**no**")
    L.append("")
    L.append("## (a) Output level, per network\n")
    L.append("| network | logit SD | R^2 train | R^2 test | R^2 linear | residual SD train (raw) | residual SD test |")
    L.append("|---|---|---|---|---|---|---|")
    for r in O.itertuples():
        L.append(f"| {r.network} | {r.logit_sd_train:.2f} | {f3(r.r2_train)} | {f3(r.r2_test)} | {f3(r.r2_linear_train)} | "
                 f"{f3(r.resid_sd_train)} ({f3(r.resid_sd_train_raw)}) | {f3(r.resid_sd_test)} |")
    L.append("")
    L.append("## (b) Part level\n")
    for d in S:
        g = P[P.dataset == d]
        L.append(f"**{NAMES[d]}**: {len(g)} parts. " + ", ".join(f"{k} {v}" for k, v in g.status.value_counts().items()) + ".")
        un = g[g.status == "unmapped"]
        for r in un.itertuples():
            L.append(f"- unmapped: {r.network} `{r.part}` (own SD {f3(r.own_sd)}, R^2 on the catalogue "
                     f"{f3(r.r2_train)}; largest blocks {r.top_blocks})")
        mr = g[g.status == "mapped, residual >= 0.10"]
        if len(mr):
            L.append("- mapped, but with a residual SD of 0.10 or more: " + "; ".join(
                f"{r.network.rsplit('-', 1)[1]} `{r.part}` ({f3(r.resid_sd)})" for r in mr.itertuples()))
        L.append("")
    L.append("Per-part numbers, including the signals each part maps to: `part_level.csv`.\n")
    L.append("## (c) Residual scan: candidate signals\n")
    if len(C):
        L.append("| data set | residual structure | networks (detected) | SD max (median) | catalogue blocks on these variables |")
        L.append("|---|---|---|---|---|")
        for r in C.itertuples():
            blk = r.catalogue_blocks_on_these_variables if isinstance(r.catalogue_blocks_on_these_variables, str) else "none"
            L.append(f"| {NAMES[r.dataset]} | {r.feature} ({r.kind}) | {r.networks} ({r.n_networks_detected}) | "
                     f"{f3(r.max_sd)} ({f3(r.median_sd)}) | {blk} |")
    else:
        L.append("No candidate signal.")
    L.append("")
    L.append("A candidate whose variables already carry a catalogue block (last column) is a finer shape "
             "of a listed signal; one with none is a signal the list does not name. Candidates are findings "
             "and have not been added to any catalogue.\n")
    gb = R[R.feature == "(all, GB)"]
    L.append("Gradient-boosting check (out-of-fold R^2 of the residual; family-wise detection uses its permutations):\n")
    L.append("| network | R^2 (out of fold) | permutation max | SD of the recovered structure | detected |")
    L.append("|---|---|---|---|---|")
    for r in gb.itertuples():
        L.append(f"| {r.network} | {f3(r.cv_gain)} | {f3(r.perm_max)} | {f3(r.sd)} | {'yes' if r.detected else 'no'} |")
    (HERE / "RESULTS.md").write_text("\n".join(L) + "\n")


if __name__ == "__main__":
    write()
