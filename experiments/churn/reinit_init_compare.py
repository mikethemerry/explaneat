"""Study E, amendment E-K (RESCUE2_REINIT_PLAN.md): N(0,1) vs fan-in-scaled
(Kaiming) re-initialisation, side by side.

Reads only the eight committed study E CSVs (``reinit_{network,feature}[_kaiming][_es].csv``)
and writes:
- ``reinit_init_comparison.csv``: one row per (level, regime, arm), plus one
  ``paired`` row per (level, regime) with the per-init Kaiming - N(0,1) test
  AUC difference (the arms share seeds and draws, so inits pair one to one);
- the generated table block in ``EXTENSIONS_RESULTS.md`` between the
  ``reinit_init_compare.py`` markers (the rest of the file is not touched).

Per arm and regime:
- equivalent count (E2: ``equivalent``; E1: ``equivalent_vs_donor_orig``);
- median delta test AUC vs the reference (E2: the evolved weights; E1: the
  alias-weights reference);
- share of inits whose test AUC reaches the reference's;
- pooled dead-unit share (dead units / hidden or grafted units over all inits);
- the median test AUC and median logit (E2) or contribution (E1) r, for context.

The paired row gives the median per-init difference, the counts of inits where
Kaiming is higher or lower, and a two-sided sign test (ties dropped). It also
checks that the references (the evolved rows, the alias-weights reference rows
and the early-stopped evolved fine-tune) agree between the arms, because they
involve no init draw.

    uv run python experiments/churn/reinit_init_compare.py
"""

from __future__ import annotations

import csv
from pathlib import Path

import numpy as np
from scipy.stats import binomtest

HERE = Path(__file__).resolve().parent
OUT = HERE / "reinit_init_comparison.csv"
RESULTS = HERE / "EXTENSIONS_RESULTS.md"
BEGIN = "<!-- BEGIN generated by reinit_init_compare.py; do not edit by hand -->"
END = "<!-- END generated by reinit_init_compare.py -->"

ARMS = {"normal": "N(0,1)", "kaiming": "Kaiming"}
# (level, regime label, file stem, epochs value in the CSV)
REGIMES = [
    ("E2", "E = 500", "reinit_network", "500"),
    ("E2", "E = 2000", "reinit_network", "2000"),
    ("E2", "early stopping", "reinit_network", "es"),
    ("E1", "E = 500", "reinit_feature", "500"),
    ("E1", "early stopping", "reinit_feature", "es"),
]
COLUMNS = [
    "kind", "level", "regime", "arm", "source_csv", "n_inits", "n_equivalent",
    "median_test_auc", "median_delta_vs_ref", "n_reach_ref", "share_reach_ref",
    "n_dead", "n_units", "dead_share", "median_r_vs_ref_function",
    "median_paired_diff", "n_kaiming_higher", "n_kaiming_lower", "n_ties", "sign_test_p",
    "references_identical", "note",
]


def csv_name(stem: str, arm: str, es: bool) -> str:
    return f"{stem}{'_kaiming' if arm == 'kaiming' else ''}{'_es' if es else ''}.csv"


def read(name: str):
    with open(HERE / name) as f:
        return list(csv.DictReader(f))


def arm_rows(level, epochs, rows):
    """Init rows of one regime keyed by the pairing key, and their references."""
    if level == "E2":
        inits = {(r["topology_seed"], r["init_seed"]): r for r in rows
                 if r["kind"] == "init" and r["epochs"] == epochs}
        refs = [(r["kind"], r["topology_seed"], r["test_auc"]) for r in rows
                if r["kind"] in ("evolved", "evolved_esft")]
    else:
        inits = {(r["case"], r["init_seed"]): r for r in rows
                 if r["kind"] == "init" and r["epochs"] == epochs}
        refs = [(r["case"], r["graft_status"], r["test_auc"]) for r in rows
                if r["kind"] == "reference"]
    return inits, sorted(refs)


def summarise(level, inits):
    rs = list(inits.values())
    f = lambda k: np.array([float(r[k]) for r in rs])  # noqa: E731
    test = f("test_auc")
    if level == "E2":
        ref, delta, eq = f("evolved_test_auc"), f("test_auc_minus_evolved"), "equivalent"
        units, rfun = f("n_hidden"), "logit_r_vs_evolved"
    else:
        ref, delta, eq = f("ref_test_auc"), f("test_auc_minus_ref"), "equivalent_vs_donor_orig"
        units, rfun = f("n_grafted_units"), "contrib_r_vs_donor_orig"
    rv = np.array([float(r[rfun]) for r in rs if r[rfun] not in ("", "nan")])
    n_dead = int(f("n_dead").sum())
    reach = int((test >= ref).sum())
    return {"n_inits": len(rs), "n_equivalent": int(sum(r[eq] == "True" for r in rs)),
            "median_test_auc": float(np.median(test)), "median_delta_vs_ref": float(np.median(delta)),
            "n_reach_ref": reach, "share_reach_ref": reach / len(rs), "n_dead": n_dead,
            "n_units": int(units.sum()), "dead_share": n_dead / units.sum(),
            "median_r_vs_ref_function": float(np.median(rv[np.isfinite(rv)]))}


def build():
    out = []
    for level, regime, stem, epochs in REGIMES:
        es = epochs == "es"
        per_arm, ref_sets = {}, {}
        for arm, label in ARMS.items():
            name = csv_name(stem, arm, es)
            inits, refs = arm_rows(level, epochs, read(name))
            per_arm[arm], ref_sets[arm] = inits, refs
            out.append({"kind": "arm", "level": level, "regime": regime, "arm": label,
                        "source_csv": name, **summarise(level, inits)})
        n, k = per_arm["normal"], per_arm["kaiming"]
        if set(n) != set(k):
            raise SystemExit(f"{level} {regime}: the arms' inits do not pair")
        d = np.array([float(k[key]["test_auc"]) - float(n[key]["test_auc"]) for key in sorted(n)])
        hi, lo = int((d > 0).sum()), int((d < 0).sum())
        p = binomtest(hi, hi + lo, 0.5).pvalue if hi + lo else float("nan")
        out.append({"kind": "paired", "level": level, "regime": regime,
                    "arm": "Kaiming - N(0,1)", "n_inits": len(d),
                    "median_paired_diff": float(np.median(d)), "n_kaiming_higher": hi,
                    "n_kaiming_lower": lo, "n_ties": int((d == 0).sum()), "sign_test_p": p,
                    "references_identical": ref_sets["normal"] == ref_sets["kaiming"],
                    "note": "per-init test AUC difference paired on (topology or case, init "
                            "seed); two-sided sign test, ties dropped"})
    return out


def write_csv(rows):
    with open(OUT, "w", newline="") as f:
        w = csv.DictWriter(f, fieldnames=COLUMNS)
        w.writeheader()
        for r in rows:
            w.writerow({c: r.get(c, "") for c in COLUMNS})
    print(f"wrote {OUT.name} ({len(rows)} rows)")


def table(rows):
    arms = {(r["level"], r["regime"], r["arm"]): r for r in rows if r["kind"] == "arm"}
    pairs = {(r["level"], r["regime"]): r for r in rows if r["kind"] == "paired"}
    lines = [BEGIN, "",
             "| Level | Regime | Init | Equivalent | Median Δ test AUC vs ref | Reach ref test AUC "
             "| Dead units | Median test AUC | Median r vs ref function |",
             "|---|---|---|---|---|---|---|---|---|"]
    for level, regime, _, _ in REGIMES:
        for label in ARMS.values():
            a = arms[(level, regime, label)]
            lines.append(
                f"| {level} | {regime} | {label} | {a['n_equivalent']}/{a['n_inits']} "
                f"| {a['median_delta_vs_ref']:+.3f} | {a['n_reach_ref']}/{a['n_inits']} "
                f"({a['share_reach_ref']:.0%}) | {a['dead_share']:.2f} "
                f"({a['n_dead']}/{a['n_units']}) | {a['median_test_auc']:.3f} "
                f"| {a['median_r_vs_ref_function']:.2f} |")
    lines += ["", "Paired Kaiming − N(0,1) test AUC, per init (same seeds and draws):", "",
              "| Level | Regime | Median difference | Kaiming higher / lower / tied | Sign test p "
              "| References identical |", "|---|---|---|---|---|---|"]
    for level, regime, _, _ in REGIMES:
        p = pairs[(level, regime)]
        lines.append(f"| {level} | {regime} | {p['median_paired_diff']:+.3f} "
                     f"| {p['n_kaiming_higher']} / {p['n_kaiming_lower']} / {p['n_ties']} "
                     f"| {p['sign_test_p']:.2g} | {'yes' if p['references_identical'] else 'NO'} |")
    lines += ["", END]
    return "\n".join(lines)


def write_block(block):
    text = RESULTS.read_text()
    if BEGIN not in text or END not in text:
        raise SystemExit(f"{RESULTS.name} has no {BEGIN!r} ... {END!r} block; add the markers "
                         "where the table belongs")
    head, rest = text.split(BEGIN, 1)
    _, tail = rest.split(END, 1)
    RESULTS.write_text(head + block + tail)
    print(f"updated the generated block in {RESULTS.name}")


def main():
    rows = build()
    write_csv(rows)
    write_block(table(rows))


if __name__ == "__main__":
    main()
